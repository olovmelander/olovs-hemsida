// Publish the Blender woodland specimens using Banvy's existing quantized GLB
// format. The index is separate from each course's surveying/selection data.
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { treeGlb } from './tree-glb.mjs';

const work = process.argv[2];
if (!work) throw Error('Pass the intermediate directory from woodland_trees.py');
const base = 'apps/golf/public/models/trees';
const { species } = JSON.parse(fs.readFileSync(path.join(base, 'realistic-v2.json'), 'utf8'));
const woodland = {}, assets = new Map();

function orientPackedBark(bytes) {
  // A submillimetre birch elbow can move across its own tangent when the
  // position is quantized. Use the exact signed integers the GPU will read.
  const jsonLength = bytes.readUInt32LE(12);
  const doc = JSON.parse(bytes.toString('utf8',20,20+jsonLength));
  const bin = bytes.byteOffset + 28 + jsonLength;
  const primitive = doc.meshes.find(m => m.name === 'trunk').primitives[0];
  const attribute = (accessor, ArrayType, componentType, stride) => {
    const a = doc.accessors[accessor], v = doc.bufferViews[a.bufferView];
    if (a.componentType !== componentType || (v.byteStride || stride) !== stride) throw Error('Unexpected bark vertex encoding');
    return new ArrayType(bytes.buffer,bin+v.byteOffset,v.byteLength/ArrayType.BYTES_PER_ELEMENT);
  };
  const p = attribute(primitive.attributes.POSITION,Int16Array,5122,8);
  const n = attribute(primitive.attributes.NORMAL,Int8Array,5120,4);
  const ids = attribute(primitive.indices,Uint16Array,5123,2);
  for (let j=0; j<ids.length; j+=3) {
    const a=ids[j]*4, b=ids[j+1]*4, c=ids[j+2]*4;
    const ax=p[b]-p[a], ay=p[b+1]-p[a+1], az=p[b+2]-p[a+2];
    const bx=p[c]-p[a], by=p[c+1]-p[a+1], bz=p[c+2]-p[a+2];
    const x=ay*bz-az*by, y=az*bx-ax*bz, z=ax*by-ay*bx;
    if (!x && !y && !z) throw Error('Collapsed bark triangle');
    if (x*(n[a]+n[b]+n[c])+y*(n[a+1]+n[b+1]+n[c+1])+z*(n[a+2]+n[b+2]+n[c+2])<0)
      [ids[j+1],ids[j+2]] = [ids[j+2],ids[j+1]];
  }
}

for (const key of ['gran', 'björk', 'al', 'ek']) {
  const { variants } = species.find(s => s.key === key);
  woodland[key] = variants.map((template, i) => {
    const tiers = {};
    for (const tier of ['hero', 'full']) {
      const model = JSON.parse(fs.readFileSync(path.join(work, `${key}-${i}-${tier}.json`), 'utf8'));
      const crown = model.crown, trunk = model.trunk;
      const tris = (crown.index.length + trunk.index.length) / 3;
      if (!Number.isInteger(tris) || tris > template.tiers[tier].tris) throw Error('Triangle budget exceeded');
      let top = -Infinity, radius = 0;
      for (const part of [crown, trunk]) {
        const count = part.position.length / 3;
        if (!Number.isInteger(count) || !count || part.uv.length !== count * 2 || part.normal.length !== count * 3 ||
            part.index.some(v => !Number.isInteger(v) || v < 0 || v >= count) ||
            [...part.position, ...part.normal, ...part.uv].some(v => !Number.isFinite(v)))
          throw Error('Invalid mesh ' + key + ' ' + tier);
        for (let j = 0; j < part.position.length; j += 3) {
          if (key==='gran' && part===crown && part.position[j+1]<0) throw Error('Spruce needles extend below the foot');
          top = Math.max(top, part.position[j + 1]);
          radius = Math.max(radius, Math.abs(part.position[j]), Math.abs(part.position[j + 2]));
        }
      }
      if (Math.abs(top-template.templateHeight) > .001 || Math.abs(radius-template.templateRadius) > .001)
        throw Error('Template envelope changed');
      const glb = treeGlb(model);
      orientPackedBark(glb);
      const sha256 = createHash('sha256').update(glb).digest('hex');
      const file = 'realistic-v2/' + sha256 + '.glb';
      assets.set(file, glb);
      tiers[tier] = { file, bytes: glb.length, sha256, tris };
    }
    return tiers;
  });
}
for (const [file, bytes] of assets) fs.writeFileSync(path.join(base, file), bytes);
fs.writeFileSync('apps/golf/src/data/woodland-tree-tiers.mjs',
  '// Generated by tools/blender-tree-study/realistic/pack_woodland_trees.mjs.\nexport default ' + JSON.stringify(woodland, null, 2) + ';\n');
console.log(assets.size, 'meshes,', Array.from(assets.values()).reduce((sum,b) => sum+b.length, 0), 'bytes');
