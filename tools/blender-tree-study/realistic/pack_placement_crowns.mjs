// The course planter historically took height, width and building clearance
// from the first visual crown. Capture those exact values once so future art
// edits cannot add or remove a tree near a roof, or rescale a stand.
import fs from 'node:fs/promises';
import { fetchGlb, fitFoliageTier } from '../../../apps/golf/src/engine/ghibli-tree-assets.mjs';
import pilot from '../../../apps/golf/src/data/playing-height-tree-tiers.mjs';

const root = new URL('../../../apps/golf/public/models/trees/', import.meta.url);
const crowns = {};
for (const name of ['realistic-v2', 'realistic-visby']) {
  const catalogue = JSON.parse(await fs.readFile(new URL(name + '.json', root)));
  for (const species of catalogue.species) {
    const form = species.variants[0];
    for (const tiers of [form.tiers, pilot[species.key]?.[0]].filter(Boolean)) {
      for (const tier of ['hero', 'full']) {
        const rec = tiers[tier];
        if (crowns[rec.sha256]) continue;
        const parts = await fetchGlb(rec.file, rec, async file => new Response(await fs.readFile(new URL(file, root))));
        fitFoliageTier(parts, form.templateHeight, form.templateRadius);
        parts.crown.computeBoundingBox();
        const { min, max } = parts.crown.boundingBox;
        crowns[rec.sha256] = { height: max.y, radius: Math.max(-min.x, max.x, -min.z, max.z), base: min.y };
      }
    }
  }
}
await fs.writeFile(new URL('../../../apps/golf/src/data/tree-placement-crowns.mjs', import.meta.url),
  '// Generated by tools/blender-tree-study/realistic/pack_placement_crowns.mjs.\nexport default ' +
  JSON.stringify(crowns, null, 2) + ';\n');
