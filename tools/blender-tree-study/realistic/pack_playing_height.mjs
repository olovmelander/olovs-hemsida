// Pack Blender's playing-height trees using the production mesh encoding.
// The indexed overlay carries only replacement tier assets. Seeds, extents,
// materials and course-specific species selections stay in the base catalogue.
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { treeGlb } from './tree-glb.mjs';

const dir = process.argv[2];
if (!dir) throw new Error('Pass the output directory of playing_height_trees.py');
const root = path.resolve('apps/golf/public/models/trees');
const base = JSON.parse(fs.readFileSync(path.join(root, 'realistic-v2.json')));
const overlay = {};
for (const species of base.species) {
  if (species.key === 'tall') continue;
  overlay[species.key] = species.variants.map((variant, index) => {
    const tiers = {};
    for (const tier of ['hero', 'full']) {
      const tree = JSON.parse(fs.readFileSync(path.join(dir, `${species.key}-${index}-${tier}.json`)));
      const tris = (tree.crown.index.length + tree.trunk.index.length) / 3;
      if (tris > variant.tiers[tier].tris) throw new Error(`${species.key} ${index} ${tier} exceeds budget`);
      const packed = treeGlb(tree), sha256 = createHash('sha256').update(packed).digest('hex');
      const file = `realistic-v2/${sha256}.glb`;
      fs.writeFileSync(path.join(root, file), packed);
      tiers[tier] = { file, bytes: packed.length, sha256, tris };
    }
    return tiers;
  });
}
fs.writeFileSync('apps/golf/src/data/playing-height-tree-tiers.mjs',
  '// Generated by tools/blender-tree-study/realistic/pack_playing_height.mjs.\nexport default ' + JSON.stringify(overlay, null, 2) + ';\n');
