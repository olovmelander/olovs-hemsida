// Pack the Blender branchlet renders into the same mip-safe cutout and
// half-resolution normal/transmission format as the detailed tree materials.
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { mobileBranchletAtlas } from './woodland_atlas_mip.mjs';

const work = process.argv[2];
if (!work) throw Error('Pass the render directory from woodland_sprigs.py');
const packed = path.join(work, 'packed');
const keys = ['ek','björk','al'];
execFileSync(process.execPath,[fileURLToPath(new URL('pack_sprigs.mjs',import.meta.url)),work,packed,'--keys',keys.join(',')],{stdio:'inherit'});
const atlas = JSON.parse(fs.readFileSync(path.join(packed, 'atlas.json'))).species;
const manifest = {};
for (const key of keys) {
  const item = atlas[key];
  function publish(content, expected) {
    const digest = createHash('sha256').update(content).digest('hex');
    if (expected && digest !== expected) throw Error('Atlas checksum changed');
    const file = 'realistic-v2/' + digest + '.png';
    fs.writeFileSync(path.join('apps/golf/public/models/trees', file),content);
    return {file, bytes: content.length, sha256: digest};
  }
  const colour = fs.readFileSync(path.join(packed,key+'.png'));
  const normals = fs.readFileSync(path.join(packed,key+'-normal.png'));
  manifest[key] = {atlas: publish(colour,item.sha256), normals:publish(normals,item.normal.sha256),
    mean:item.mean, lowAtlas:publish(mobileBranchletAtlas(colour,512))};
}
fs.writeFileSync('apps/golf/src/data/woodland-sprigs.mjs',
  '// Generated by tools/blender-tree-study/realistic/pack_woodland_sprigs.mjs.\nexport default ' + JSON.stringify(manifest,null,2)+';\n');
