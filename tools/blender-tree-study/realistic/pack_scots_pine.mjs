// Pack the two Blender pine families into the same verified asset format as
// their standard models, including the shared 2×2 UV layout on both tiers.
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { treeGlb } from './tree-glb.mjs';
import { decodePNG } from '../../../geobuild/png.mjs';
import { encodeRGBA } from './make_leaf_atlas.mjs';

const dir = process.argv[2];
if (!dir) throw new Error('Pass the directory generated by scots_pine.py and scots_pine_sprigs.py');
const root = path.resolve('apps/golf/public/models/trees');
const packed = path.join(dir, 'packed');
execFileSync(process.execPath, [fileURLToPath(new URL('./pack_sprigs.mjs', import.meta.url)), dir, packed,
  '--keys', 'inland,coastal'], { stdio: 'inherit' });
const atlases = JSON.parse(fs.readFileSync(path.join(packed, 'atlas.json'))).species;

// Keep needle coverage byte-for-byte. One sRGB code of colour precision is
// below the material's leaf variation and saves mobile transfer/storage.
function colourAtlas(filename) {
  const { width, height, data } = decodePNG(fs.readFileSync(filename));
  for (let i = 0; i < data.length; i += 4) for (let c = 0; c < 3; c++) {
    const v = data[i + c];
    if (v % 2 && v !== 255) data[i + c] = v % 4 === 1 ? v - 1 : v + 1;
  }
  return encodeRGBA(width, height, data);
}

function publish(bytes, ext) {
  const sha256 = createHash('sha256').update(bytes).digest('hex');
  const file = `realistic-v2/${sha256}.${ext}`;
  fs.writeFileSync(path.join(root, file), bytes);
  return { file, bytes: bytes.length, sha256 };
}

const families = {};
for (const [family, sourceFile] of [['inland', 'realistic-v2.json'], ['coastal', 'realistic-visby.json']]) {
  const source = JSON.parse(fs.readFileSync(path.join(root, sourceFile))).species.find(s => s.key === 'tall');
  const foliage = {
    atlas: publish(colourAtlas(path.join(packed, family + '.png')), 'png'),
    normals: publish(fs.readFileSync(path.join(packed, family + '-normal.png')), 'png'),
    mean: atlases[family].mean,
  };
  const variants = source.variants.map((original, index) => {
    const tiers = {};
    for (const tier of ['hero', 'full']) {
      const data = JSON.parse(fs.readFileSync(path.join(dir, `${family}-${index}-${tier}.json`)));
      const tris = (data.crown.index.length + data.trunk.index.length) / 3;
      if (tris > original.tiers[tier].tris) throw new Error(`${family} ${index} ${tier}: excess triangles`);
      tiers[tier] = { ...publish(treeGlb(data), 'glb'), tris };
    }
    return tiers;
  });
  families[family] = { foliage, variants };
}
fs.writeFileSync('apps/golf/src/data/scots-pine-assets.mjs',
  '// Generated by tools/blender-tree-study/realistic/pack_scots_pine.mjs.\nexport default ' + JSON.stringify(families, null, 2) + ';\n');
