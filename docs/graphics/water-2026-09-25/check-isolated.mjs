// The water batch's shaders in isolated scenes (isolated.html), on WebGL2 and on
// WebGPU with reversed depth:
//  - the before: the player's water shading with both before switches is main's
//    own (generated from git at the baseline), pixel for pixel, lake, pond and sea;
//  - the sun's road: the shader's expected glitter is nordic-water.mjs's form; on
//    a lake at golden hour the road beyond the dabs is that expectation, and it
//    runs on through the change from dabs without a hole, where main's dabs thin;
//  - the far shore: the reflected wood is where the shader says, round the whole
//    horizon, darkens a lake's far water and leaves the open sea alone;
//  - the wind: the patches' chop is the pattern's, over its mean, fading far off;
//    and the ripples drift with the offsets the air carries, downwind.
// Software rendering by default, BANVY_GPU=1 for the real adapter. Run from the
// repository root: node docs/graphics/water-2026-09-25/check-isolated.mjs
import fs from 'node:fs';
import { spawn, execFileSync } from 'node:child_process';
import { chromium } from 'playwright-core';
import { browserArgs, browserExecutable, GPU } from '../../../tools/browser-args.mjs';
import { expectedGlitterAt, patchChopOf, NORDIC_WATER, SLOPE_SCALE } from '../../../apps/golf/src/engine/nordic-water.mjs';
import { ATMOSPHERE_PRESETS } from '../../../apps/golf/src/engine/atmosphere-presets.mjs';
import { paintedAtmosphere } from '../../../apps/golf/src/engine/painted-world-palette.mjs';

const dir = 'docs/graphics/water-2026-09-25';
const out = process.argv[2] || `${dir}/isolated-check.json`;
const baseline = '6158f6b1';
const port = 8694;

/* main's own water shading at the baseline, as a module the page can import */
const main = execFileSync('git', ['show', `${baseline}:apps/golf/src/main.js`], { encoding: 'utf8', maxBuffer: 64 << 20 });
const fn = main.slice(main.indexOf('function makeWater('));
const body = fn.slice(fn.indexOf("  const aSh = attribute('aShore', 'float');"), fn.indexOf('.clamp(0.4, 1);') + '.clamp(0.4, 1);'.length);
fs.writeFileSync(`${dir}/old-water.gen.mjs`, `// generated by check-isolated.mjs from main.js at ${baseline}; not committed
import { attribute, cameraPosition, color, float, mix, normalize, oneMinus, positionWorld, pow, reflect, saturate, smoothstep, texture, time, vec2, vec3 } from 'three/tsl';
import { paintedWaterShallow, paintedWaterDeep, paintedWaterSparkle, paintedWaterLight } from '/apps/golf/src/engine/painted-world-lighting.mjs';
export function oldWaterShading({ WATERN, DETAIL, uSun, waterLighting, uWaterChop, uWaterGlint, CLOUD, ocean, showBed }) {
  const m = {};
${body}
  return { colorNode: m.colorNode, opacity };
}
`);

const server = spawn(process.execPath, ['tools/serve.mjs', '.', String(port)], { stdio: 'ignore' });
await new Promise(r => setTimeout(r, 1200));
const argsFor = backend => backend === 'webgpu' ? [...browserArgs(), '--enable-unsafe-webgpu',
  ...(GPU ? [] : ['--enable-features=Vulkan', '--use-vulkan=swiftshader', '--use-webgpu-adapter=swiftshader', '--disable-vulkan-surface'])] : browserArgs();
const report = { adapter: GPU ? 'gpu' : 'swiftshader', baseline, backends: {} };
let failed = false;
const check = (backend, label, ok, detail) => {
  report.backends[backend].checks.push({ label, ok, ...detail });
  if (!ok) failed = true;
  console.log(`${backend} ${ok ? 'ok  ' : 'FAIL'} ${label} ${JSON.stringify(detail).slice(0, 500)}`);
};
const r4 = v => Math.round(v * 1e4) / 1e4;
const lum = (px, k) => 0.2126 * px[k] + 0.7152 * px[k + 1] + 0.0722 * px[k + 2];
const smooth = (a, b, x) => { const t = Math.min(1, Math.max(0, (x - a) / (b - a))); return t * t * (3 - 2 * t); };
const mean = a => a.reduce((s, v) => s + v, 0) / Math.max(1, a.length);
const painted = name => paintedAtmosphere(name, ATMOSPHERE_PRESETS[name]);
const diff = (a, b) => { let max = 0, n = 0; for (let k = 0; k < a.length; k++) { const d = Math.abs(a[k] - b[k]); if (d > 0) n++; if (d > max) max = d; } return { maxDiff: max, differingValues: n }; };

/* an independent reading of the tree line (nordic-water.mjs treeLineShare), for the grid */
const treeLineAt = (az, up) => {
  const broad = Math.sin(az * 5 + Math.sin(az * 2) * 1.4) * 0.5 + 0.5, fine = Math.sin(az * 13 + 1.7) * 0.5 + 0.5;
  const top = (broad * 0.5 + fine * 0.15 + 0.6) * NORDIC_WATER.treeLine.height;
  return 1 - smooth(top * 0.55, top * 1.1, up);
};

const shots = [];
try {
  for (const backend of ['webgl2', 'webgpu']) {
    report.backends[backend] = { checks: [] };
    const browser = await chromium.launch({ ...browserExecutable(), args: argsFor(backend) });
    const page = await browser.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(String(e)));
    page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
    await page.goto(`http://127.0.0.1:${port}/${dir}/isolated.html?backend=${backend}`, { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => window.__result, null, { timeout: 600000, polling: 500 });
    const result = await page.evaluate(() => window.__result);
    if (result.error) { check(backend, 'renders', false, { error: result.error }); await browser.close(); continue; }
    const { W, H } = result, N = W * H;
    const call = (fn, arg) => page.evaluate(([f, a]) => window[f](a), [fn, arg]);

    /* ------------------------------------------------------------ the before */
    const befores = {};
    for (const [name, arg] of Object.entries({ lake: {}, pond: { fetch: 0 }, sea: { ocean: true } })) {
      for (const [preset, view] of [['golden', 'road'], ['noon', 'across']]) {
        const was = await call('__water', { version: 'main', preset, view, ...arg });
        const now = await call('__water', { version: 'new', preset, view, ...arg });
        befores[`${name} ${preset}`] = diff(was.px, now.px);
      }
    }
    check(backend, 'with both before switches the player\'s water is main\'s own, pixel for pixel: lake, pond and sea, golden hour and noon',
      Object.values(befores).every(d => d.maxDiff === 0), befores);

    /* ------------------------------------------------------------ the sun's road */
    const glitterGrid = await call('__glitterGrid');
    let glitterErr = 0;
    for (let k = 0; k < N; k++) {
      const u = glitterGrid[k * 4 + 1], v = glitterGrid[k * 4 + 2];
      glitterErr = Math.max(glitterErr, Math.abs(glitterGrid[k * 4] - expectedGlitterAt(v * 0.2, Math.tan(u * 0.6))));
    }
    check(backend, 'the shader\'s expected glitter is nordic-water.mjs\'s form over tilts to 34 degrees and spreads to 0.2',
      glitterErr < 0.004, { maxError: r4(glitterErr) });

    const pos = await call('__waterPositions', { view: 'road', preset: 'golden' });
    const golden = painted('golden'), sun = new Float64Array(golden.dir), sl = Math.hypot(...golden.dir);
    const L = [sun[0] / sl, sun[1] / sl, sun[2] / sl], cam = [0, 3, 0];
    const road = async (version, nordic, wind) => {
      const on = await call('__water', { version, nordic, wind, preset: 'golden', view: 'road', glint: 1 });
      const off = await call('__water', { version, nordic, wind, preset: 'golden', view: 'road', glint: 0 });
      const scale = lum(on.sun, 0) * on.sparkle * on.light;
      const bins = new Map();
      for (let k = 0; k < N; k++) {
        const x = pos[k * 4], y = pos[k * 4 + 1], z = pos[k * 4 + 2];
        if (!(Math.abs(x) + Math.abs(z) > 0)) continue;
        const d = Math.hypot(x - cam[0], y - cam[1], z - cam[2]);
        /* the expectation here: the flat water's half vector, and the spread the shader reckons */
        const V = [(cam[0] - x) / d, (cam[1] - y) / d, (cam[2] - z) / d], Hl = Math.hypot(V[0] + L[0], V[1] + L[1], V[2] + L[2]);
        const hy = Math.max(1e-3, (V[1] + L[1]) / Hl), t = Math.sqrt(Math.max(0, 1 - hy * hy)) / hy;
        const near = 1 - smooth(90, 900, d), w1 = near * 0.45 + 0.30, w3 = near * 0.30 + 0.16;
        const sigma = Math.sqrt(w1 * w1 + w3 * w3 + 0.49 + 0.81) * 0.55 * SLOPE_SCALE;
        const expected = expectedGlitterAt(sigma, t);
        if (expected < 0.05) continue;
        const bin = Math.min(9, Math.floor(Math.log(d / 30) / Math.log(1.6)));
        if (bin < 0) continue;
        const e = bins.get(bin) ?? { d: [], measured: [], expected: [] };
        e.d.push(d); e.measured.push((lum(on.px, k * 4) - lum(off.px, k * 4)) / scale); e.expected.push(expected);
        bins.set(bin, e);
      }
      return [...bins.entries()].sort((a, b) => a[0] - b[0]).map(([, e]) => ({ metres: Math.round(mean(e.d)), pixels: e.d.length, measured: r4(mean(e.measured)), expected: r4(mean(e.expected)), ratio: r4(mean(e.measured) / mean(e.expected)) }));
    };
    /* the lake without its patches, so the spread is the one reckoned here */
    const roadAfter = await road('new', true, false), roadMain = await road('main');
    const far = roadAfter.filter(b => b.metres > 520), band = roadAfter.filter(b => b.pixels > 30);
    const steps = band.slice(1).map((b, i) => b.measured / Math.max(1e-6, band[i].measured));
    check(backend, 'on a lake at golden hour the road beyond the dabs is their expectation, and runs on through the change without a hole',
      far.length > 0 && far.every(b => Math.abs(b.ratio - 1) < 0.03) && band.every(b => b.ratio > 0.6 && b.ratio < 1.5),
      { road: roadAfter, mainRoad: roadMain, stepRatios: steps.map(r4) });

    /* ------------------------------------------------------------ the far shore */
    const treeGrid = await call('__treeGrid');
    let treeErr = 0;
    for (let k = 0; k < N; k++) {
      const u = treeGrid[k * 4 + 1], v = treeGrid[k * 4 + 2];
      treeErr = Math.max(treeErr, Math.abs(treeGrid[k * 4] - treeLineAt((u * 2 - 1) * Math.PI, v * 0.12)));
    }
    /* the far water of a lake at noon (glint off, so only the reflection differs), and the open sea */
    const across = await call('__waterPositions', { view: 'across', preset: 'noon' });
    const shoreRows = [];
    for (let k = 0; k < N; k++) { const z = across[k * 4 + 2], x = across[k * 4]; if (Math.abs(x) + Math.abs(z) > 0 && Math.hypot(x, z - 1200) > 1100) shoreRows.push(k); }
    const lakeBefore = await call('__water', { version: 'new', preset: 'noon', view: 'across', glint: 0 });
    const lakeAfter = await call('__water', { version: 'new', nordic: true, preset: 'noon', view: 'across', glint: 0 });
    const seaBefore = await call('__water', { version: 'new', ocean: true, preset: 'noon', view: 'across', glint: 0 });
    const seaAfter = await call('__water', { version: 'new', ocean: true, nordic: true, preset: 'noon', view: 'across', glint: 0 });
    const farLake = { before: r4(mean(shoreRows.map(k => lum(lakeBefore.px, k * 4)))), after: r4(mean(shoreRows.map(k => lum(lakeAfter.px, k * 4)))) };
    /* and the more so toward the horizon, where more of the reflection is the shore: 1.1-1.5 km off against 2 km and more */
    const distanceOf = k => Math.hypot(across[k * 4], across[k * 4 + 2] - 1200);
    const ratioIn = (lo, hi) => { const ks = shoreRows.filter(k => distanceOf(k) >= lo && distanceOf(k) < hi); return r4(mean(ks.map(k => lum(lakeAfter.px, k * 4))) / mean(ks.map(k => lum(lakeBefore.px, k * 4)))); };
    const byDistance = { '1.1-1.5 km': ratioIn(1100, 1500), '2 km and more': ratioIn(2000, 1e9) };
    const sea = diff(seaBefore.px, seaAfter.px);
    check(backend, 'the far shore\'s wood stands where the shader says round the whole horizon, darkens a lake\'s far water toward the horizon and leaves the open sea alone',
      treeErr < 0.004 && shoreRows.length > 1000 && farLake.after < 0.92 * farLake.before
        && byDistance['2 km and more'] < byDistance['1.1-1.5 km'] && sea.maxDiff === 0,
      { gridMaxError: r4(treeErr), farWaterPixels: shoreRows.length, farLake, byDistance, sea });

    /* ------------------------------------------------------------ the wind */
    const bytes = result.patternBytes, S = Math.round(Math.sqrt(bytes.length));
    const texel = (i, j) => bytes[((j % S + S) % S) * S + ((i % S + S) % S)] / 255;
    const sample = (u, v) => { const x = u * S - 0.5, y = v * S - 0.5, i = Math.floor(x), j = Math.floor(y), fx = x - i, fy = y - j;
      const m = (a, b, t) => a + (b - a) * t; return m(m(texel(i, j), texel(i + 1, j), fx), m(texel(i, j + 1), texel(i + 1, j + 1), fx), fy); };
    let patchMean = 0;
    for (const b of bytes) patchMean += patchChopOf(b / 255);
    patchMean /= bytes.length;
    const P = NORDIC_WATER.patches, patches = {};
    for (const [distance, offset] of [[100, [0, 0]], [100, [431, -210]], [1000, [431, -210]], [2000, [0, 0]]]) {
      const grid = await call('__patchGrid', { distance, offset });
      let err = 0, lo = Infinity, hi = -Infinity;
      for (let k = 0; k < N; k++) {
        const u = grid[k * 4 + 1], v = grid[k * 4 + 2], x = (u - 0.5) * 3000, z = (v - 0.5) * 3000;
        const value = sample((x - offset[0]) / P.tileMetres, (z - offset[1]) / P.tileMetres);
        const expected = patchChopOf(value) / patchMean * (1 - smooth(P.fadeMetres[0], P.fadeMetres[1], distance)) + smooth(P.fadeMetres[0], P.fadeMetres[1], distance);
        err = Math.max(err, Math.abs(grid[k * 4] - expected)); lo = Math.min(lo, grid[k * 4]); hi = Math.max(hi, grid[k * 4]);
      }
      patches[`${distance} m, offset ${offset}`] = { maxError: r4(err), range: [r4(lo), r4(hi)] };
    }
    /* the ripples drift: offsets for a world shift D on every layer move the whole picture by D */
    const down = await call('__waterPositions', { view: 'down', preset: 'noon' });
    const flowFor = D => [...NORDIC_WATER.layers, NORDIC_WATER.foam].map(([scale]) => [D[0] * scale, D[1] * scale]);
    const still = await call('__water', { version: 'new', wind: true, preset: 'noon', view: 'down', glint: 0, flow: flowFor([0, 0]) });
    const moved = await call('__water', { version: 'new', wind: true, preset: 'noon', view: 'down', glint: 0, flow: flowFor([4, -3]) });
    /* where does each pixel of the moved picture come from: the shift, in metres, that best aligns the two */
    const mpp = 96 / W, at = (px, x, y) => lum(px, (y * W + x) * 4);
    let best = null;
    for (let sy = -20; sy <= 20; sy++) for (let sx = -25; sx <= 25; sx++) {
      let e = 0;
      for (let y = 40; y < H - 40; y += 2) for (let x = 60; x < W - 60; x += 2) { const dd = at(moved.px, x, y) - at(still.px, x - sx, y - sy); e += dd * dd; }
      if (!best || e < best.e) best = { sx, sy, e };
    }
    /* the pixel shift in world metres, read off the positions */
    const k0 = (135 * W + 240) * 4, k1 = ((135 + best.sy) * W + 240 + best.sx) * 4;
    const shift = [r4(down[k1] - down[k0]), r4(down[k1 + 2] - down[k0 + 2])];
    check(backend, 'the patches\' chop is the pattern\'s over its mean, carried by its offset and fading far off; the ripples drift by the offsets the air carries',
      Object.values(patches).every(p => p.maxError < 0.01) && patches['2000 m, offset 0,0'].range[1] - patches['2000 m, offset 0,0'].range[0] < 1e-3
        && Math.abs(shift[0] - 4) < 2 * mpp && Math.abs(shift[1] + 3) < 2 * mpp,
      { patches, drift: { asked: [4, -3], found: shift, metresPerPixel: r4(mpp) } });

    check(backend, 'no page errors', errors.length === 0, { errors: errors.slice(0, 3) });

    if (backend === 'webgl2') {
      const picture = async label => shots.push({ label, png: (await page.locator('canvas').first().screenshot()).toString('base64') });
      const gust = flowFor([0, 0]);
      for (const preset of ['golden', 'noon']) for (const on of [false, true]) {
        await call('__picture', { preset, nordic: on, wind: on, patch: [260, 140], flow: gust });
        await picture(`${preset === 'golden' ? 'golden hour' : 'noon'}, ${on ? 'Nordic water' : 'before'}`);
      }
      const jpg = await page.evaluate(async shots => {
        const images = await Promise.all(shots.map(async s => { const im = new Image(); im.src = `data:image/png;base64,${s.png}`; await im.decode(); return im; }));
        const w = images[0].width, h = images[0].height, c = document.createElement('canvas');
        c.width = w * 2; c.height = h * Math.ceil(images.length / 2);
        const g = c.getContext('2d');
        images.forEach((im, i) => {
          const x = (i % 2) * w, y = Math.floor(i / 2) * h;
          g.drawImage(im, x, y);
          g.font = '14px sans-serif';
          const width = g.measureText(shots[i].label).width + 12;
          g.fillStyle = 'rgba(0,0,0,.55)'; g.fillRect(x + 6, y + 6, width, 22);
          g.fillStyle = '#fff'; g.fillText(shots[i].label, x + 12, y + 22);
        });
        return c.toDataURL('image/jpeg', 0.86).split(',')[1];
      }, shots);
      fs.writeFileSync(`${dir}/lakes.jpg`, Buffer.from(jpg, 'base64'));
    }
    await browser.close();
  }
} finally {
  server.kill();
  fs.rmSync(`${dir}/old-water.gen.mjs`, { force: true });
}
fs.writeFileSync(out, JSON.stringify(report, null, 1) + '\n');
console.log(failed ? 'isolated check FAILED' : `isolated check passed -> ${out}`);
process.exitCode = failed ? 1 : 0;
