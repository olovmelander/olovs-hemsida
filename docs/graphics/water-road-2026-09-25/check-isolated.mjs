// The water road pass in isolated scenes (isolated.html): the player's own water,
// sky, haze, cloud shadows, wind patches and tone mapping over an open sea, from a
// player's camera, on WebGL2 and on WebGPU with reversed depth:
//  - the before: with all four befores the player's water is main's own
//    (water-shading.mjs generated from git at the baseline), value for value;
//  - the road: seen as the owner saw it (golden hour, 180 m up, the coast 450 m
//    ahead) it runs unbroken from the coast to the horizon, where main's was cut
//    into bars by the clouds' shadows, and the clouds leave it alone under a low
//    sun; it brightens toward the horizon; under a high sun a cloud's shade puts
//    it out as before;
//  - the open sea mirrors no far shore, and nothing else changes;
//  - the mirror warms the water toward a low sun and nowhere else;
//  - the relief shows the waves from above, fading far off and under a weak sun;
//  - the road is as steady far off as main's glow, with the wind's drift and the
//    camera's flight.
// And pictures through the app's own tone mapping (and, for the desktop, glow).
// Software rendering by default, BANVY_GPU=1 for the real adapter. Run from the
// repository root: node docs/graphics/water-road-2026-09-25/check-isolated.mjs
import fs from 'node:fs';
import { spawn, execFileSync } from 'node:child_process';
import { chromium } from 'playwright-core';
import { browserArgs, browserExecutable, GPU } from '../../../tools/browser-args.mjs';
import { cloudPatternTexture, cloudShadowOf, coverThreshold, cloudSunlight, CLOUD_SHADOW } from '../../../apps/golf/src/engine/cloud-shadow.mjs';
import { createWaterMotion, stepWaterMotion } from '../../../apps/golf/src/engine/nordic-water.mjs';
import { WATER_ROAD, roadGrazing } from '../../../apps/golf/src/engine/water-road.mjs';
import { ATMOSPHERE_PRESETS } from '../../../apps/golf/src/engine/atmosphere-presets.mjs';
/* a hex colour in linear light, as three's Color takes it */
const linear = hex => [16, 8, 0].map(shift => { const c = ((hex >> shift) & 255) / 255; return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4; });
import { paintedAtmosphere } from '../../../apps/golf/src/engine/painted-world-palette.mjs';

const dir = 'docs/graphics/water-road-2026-09-25';
const out = process.argv[2] || `${dir}/isolated-check.json`;
const baseline = 'b7619256';
const port = 8706;
/* a portrait view whose rows are whole 256-byte blocks in both read-backs (8 bytes a pixel in half float, 16 in
   float): WebGPU copies a texture out in such blocks, and a row that ends mid-block skews every row after it */
const W = 384, H = 640;
const BACKENDS = (process.env.BANVY_BACKENDS || 'webgl2,webgpu').split(',');
const painted = name => paintedAtmosphere(name, ATMOSPHERE_PRESETS[name]);

/* main's own water shading at the baseline; the modules it imports are unchanged since, so it shares them */
for (const shared of ['nordic-water.mjs', 'painted-world-lighting.mjs', 'cloud-shadow.mjs', 'aerial-perspective.mjs', 'water-lighting.mjs'])
  execFileSync('git', ['diff', '--quiet', baseline, '--', `apps/golf/src/engine/${shared}`]);
const mainShading = execFileSync('git', ['show', `${baseline}:apps/golf/src/engine/water-shading.mjs`], { encoding: 'utf8' })
  .replaceAll("from './", "from '/apps/golf/src/engine/");
const generated = `${dir}/main-water.gen.mjs`;
fs.writeFileSync(generated, `// generated by check-isolated.mjs from water-shading.mjs at ${baseline}; not committed\n${mainShading}
export * as nordic from '/apps/golf/src/engine/nordic-water.mjs';\n`);

const server = spawn(process.execPath, ['tools/serve.mjs', '.', String(port)], { stdio: 'ignore' });
await new Promise(r => setTimeout(r, 1200));
const argsFor = backend => backend === 'webgpu' ? [...browserArgs(), '--enable-unsafe-webgpu',
  ...(GPU ? [] : ['--enable-features=Vulkan', '--use-vulkan=swiftshader', '--use-webgpu-adapter=swiftshader', '--disable-vulkan-surface'])] : browserArgs();
const report = { adapter: GPU ? 'gpu' : 'swiftshader', baseline, constants: WATER_ROAD, backends: {} };
let failed = false;
const check = (backend, label, ok, detail) => {
  report.backends[backend].checks.push({ label, ok, ...detail });
  if (!ok) failed = true;
  console.log(`${backend} ${ok ? 'ok  ' : 'FAIL'} ${label} ${JSON.stringify(detail).slice(0, 600)}`);
};
const decode = s => { const b = Buffer.from(s, 'base64'); return new Float32Array(new Uint8Array(b).buffer); };
const lum = (a, k) => 0.2126 * a[k] + 0.7152 * a[k + 1] + 0.0722 * a[k + 2];
const r3 = v => Math.round(v * 1000) / 1000;
const median = v => { const s = [...v].sort((a, b) => a - b); return s.length ? s[Math.floor(s.length / 2)] : null; };
const quantile = (v, f) => { const s = [...v].sort((a, b) => a - b); return s.length ? s[Math.floor(f * (s.length - 1))] : null; };

/* the views */
const OWNER = { preset: 'golden', height: 180, pitch: -12, back: 450 };
const LOW = { preset: 'golden', height: 3, pitch: -1, back: -200 };
const MID = { preset: 'golden', height: 40, pitch: -6, back: -100 };
const NOON_ABOVE = { preset: 'noon', height: 120, pitch: -55, back: -400 };
const STEEP = { preset: 'host', height: 60, pitch: -45, back: -300, yaw: 90 };
const STEEP_FAR = { preset: 'host', height: 250, pitch: -25, back: -600, yaw: 180 };
/* a pixel of visible sea in a positions read-back: drawn, and not the land in front of it (distance 0) */
const isSea = (w, i) => w[i * 4 + 3] !== 0 && w[i * 4 + 2] > 0;
const BEFORE = { road: false, mirror: false, relief: false, seaOpen: false };

/* the clouds' pattern in the shader's own terms, for a pixel on the sea (y = 0) */
const { bytes } = cloudPatternTexture();
const cloudValue = (x, z, offset) => {
  const S = CLOUD_SHADOW.size, u = ((x - offset[0]) / CLOUD_SHADOW.tileMetres) * S - 0.5, v = ((z - offset[1]) / CLOUD_SHADOW.tileMetres) * S - 0.5;
  const i0 = Math.floor(u), j0 = Math.floor(v), fu = u - i0, fv = v - j0;
  const at = (i, j) => bytes[(((j % S) + S) % S) * S + (((i % S) + S) % S)] / 255;
  return (at(i0, j0) * (1 - fu) + at(i0 + 1, j0) * fu) * (1 - fv) + (at(i0, j0 + 1) * (1 - fu) + at(i0 + 1, j0 + 1) * fu) * fv;
};

const shots = {};
try {
  for (const backend of BACKENDS) {
    report.backends[backend] = { checks: [] };
    const browser = await chromium.launch({ ...browserExecutable(), args: argsFor(backend) });
    const page = await browser.newPage({ viewport: { width: W, height: H } });
    const errors = [];
    page.on('pageerror', e => errors.push(String(e).slice(0, 300)));
    page.on('console', m => { if (m.type() === 'error') errors.push(m.text().slice(0, 300)); });
    await page.goto(`http://127.0.0.1:${port}/${dir}/isolated.html?backend=${backend}&w=${W}&h=${H}`, { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => window.__result, null, { timeout: 900000, polling: 500 });
    const ready = await page.evaluate(() => window.__result);
    if (!ready.ready || !ready.main) throw new Error(`${backend}: ${ready.error || 'main shading missing'}`);
    const reads = [];
    const read = async options => {
      const r = await page.evaluate(o => window.__read(o), options);
      reads.push({ settled: r.settled, renders: r.renders });
      return decode(r.px);
    };
    /* x and z come back up the scale by the page's offset: taken back down here */
    const where = async options => {
      const w = decode((await page.evaluate(o => window.__where(o), options)).px);
      for (let i = 0; i < W * H; i++) if (w[i * 4 + 3] !== 0) { w[i * 4] -= ready.whereOffset; w[i * 4 + 1] -= ready.whereOffset; }
      return w;
    };

    /* THE BEFORE: all four befores are main's water, value for value, with the clouds and patches as they are */
    {
      const rows = {};
      for (const [name, view] of Object.entries({ owner: OWNER, low: LOW, noonAbove: NOON_ABOVE, steep: STEEP })) {
        const mine = await read({ ...view, ...BEFORE }), theirs = await read({ ...view, version: 'main' });
        let differing = 0, max = 0;
        for (let k = 0; k < mine.length; k++) { const d = Math.abs(mine[k] - theirs[k]); if (d > 0) differing++; if (d > max) max = d; }
        rows[name] = { differing, maxDiff: max };
      }
      check(backend, 'with its four befores the water is main\'s own, value for value', Object.values(rows).every(r => r.differing === 0), { rows });
    }

    /* THE ROAD, as the owner saw it. Its light is the picture with the sparkle less the picture without it. */
    const ownerWhere = await where(OWNER);
    const roadOf = async options => {
      const on = await read({ ...options, glint: 1 }), off = await read({ ...options, glint: 0 });
      const road = new Float32Array(W * H);
      for (let i = 0; i < W * H; i++) road[i] = isSea(ownerWhere, i) ? Math.max(0, lum(on, i * 4) - lum(off, i * 4)) : 0;
      return road;
    };
    /* each screen row of sea, from the horizon to the coast: the road's light across it; a bar is a row far
       under the median of the rows about it */
    const profile = road => {
      const rows = [];
      for (let y = 0; y < H; y++) {
        let sea = 0, sum = 0, d = 0;
        for (let x = 0; x < W; x++) { const i = y * W + x; if (!isSea(ownerWhere, i)) continue; sea++; sum += road[i]; d += ownerWhere[i * 4 + 2]; }
        if (sea > W * 0.9) rows.push({ y, sum, distance: d / sea });
      }
      let bars = 0, deepest = 1;
      rows.forEach((r, k) => {
        const around = rows.slice(Math.max(0, k - 12), k + 13).map(q => q.sum), m = median(around);
        const ratio = m > 1e-3 ? r.sum / m : 1;
        if (ratio < 0.75) bars++;
        deepest = Math.min(deepest, ratio);
      });
      return { rows: rows.length, bars, deepest: r3(deepest), rowsFrom: r3(rows[0]?.distance ?? 0), rowsTo: r3(rows.at(-1)?.distance ?? 0) };
    };
    {
      const now = await roadOf({ ...OWNER, ...BEFORE }), mine = await roadOf(OWNER), clear = await roadOf({ ...OWNER, clouds: false });
      const pNow = profile(now), pMine = profile(mine);
      let sameInTheClear = true;
      for (let i = 0; i < W * H; i++) if (mine[i] !== clear[i]) { sameInTheClear = false; break; }
      check(backend, 'the owner\'s road runs unbroken from the coast to the horizon, and a low sun\'s clouds leave it alone',
        pNow.bars > 0 && pMine.bars === 0 && sameInTheClear, { main: pNow, road: pMine, cloudsLeaveItAlone: sameInTheClear });

    }

    /* TOWARD GRAZING it brightens as the water's reflectance does. Against the dabs as they were before the water batch
       (the same ripples, in their near-white), every glinting pixel of the road is brighter by the road's own grazing
       factor at the angle the eye meets it (V.H, from the pixel's place), times the sun's colour over the old white:
       the haze and the ripples cancel */
    {
      const view = { ...MID, clouds: false }, w = await where(view);
      const newOn = await read({ ...view, glint: 1 }), newOff = await read({ ...view, glint: 0 });
      const oldView = { ...view, ...BEFORE, nordic: false, seaOpen: true };
      const oldOn = await read({ ...oldView, glint: 1 }), oldOff = await read({ ...oldView, glint: 0 });
      const p = painted(MID.preset), L = p.dir.map(v => v / Math.hypot(...p.dir));
      const sunColour = linear(p.sun), top = Math.max(...sunColour);
      const lumOf = c => 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
      const colourRatio = lumOf(sunColour) / top / lumOf(linear(0xfff4d9));
      const errs = [], factors = [];
      for (let i = 0; i < W * H; i++) {
        if (!isSea(w, i)) continue;
        const old = lum(oldOn, i * 4) - lum(oldOff, i * 4);
        if (old < 0.02) continue;
        const x = w[i * 4], z = w[i * 4 + 1], V = [-x, MID.height, -z], lv = Math.hypot(...V);
        const Hv = V.map((v, k) => v / lv + L[k]), lh = Math.hypot(...Hv);
        const vh = V.reduce((s2, v, k) => s2 + v / lv * Hv[k] / lh, 0);
        const factor = roadGrazing(vh);
        factors.push(factor);
        errs.push(Math.abs((lum(newOn, i * 4) - lum(newOff, i * 4)) / old / (factor * colourRatio) - 1));
      }
      check(backend, 'the road brightens toward grazing by the water\'s reflectance, glint for glint', errs.length > 500 && median(errs) < 0.02,
        { glints: errs.length, grazingFactor: { least: r3(Math.min(...factors)), median: r3(median(factors)), most: r3(Math.max(...factors)) },
          colourRatio: r3(colourRatio), medianError: r3(median(errs)), error90: r3(quantile(errs, 0.9)) });
    }

    /* UNDER A HIGH SUN a cloud's shade puts the glitter out, as the pattern says, as it always did */
    {
      const p = painted('noon'), c = cloudShadowOf(p), threshold = coverThreshold(bytes, c.cover);
      /* the offset that lays a shadow's edge across the glitter: half of its pixels shaded */
      const w = await where(NOON_ABOVE);
      const clear0 = await read({ ...NOON_ABOVE, glint: 1, clouds: false }), dark0 = await read({ ...NOON_ABOVE, glint: 0, clouds: false });
      const glints = [];
      for (let i = 0; i < W * H; i += 7) if (isSea(w, i) && lum(clear0, i * 4) - lum(dark0, i * 4) > 0.05) glints.push([w[i * 4], w[i * 4 + 1]]);
      let offset = [0, 0], best = -1;
      for (let ox = 0; ox < 4096; ox += 64) for (let oz = 0; oz < 4096; oz += 64) {
        const shaded = glints.filter(([x, z]) => cloudSunlight(cloudValue(x, z, [ox, oz]), threshold, c.opacity) < 0.99).length / glints.length;
        const score = Math.min(shaded, 1 - shaded);
        if (score > best) { best = score; offset = [ox, oz]; }
      }
      const view = { ...NOON_ABOVE, cloudOffset: offset };
      const on = await read({ ...view, glint: 1 }), off = await read({ ...view, glint: 0 });
      const clearOn = await read({ ...view, glint: 1, clouds: false });
      const errs = [];
      let shaded = 0;
      for (let i = 0; i < W * H; i++) {
        if (!isSea(w, i)) continue;
        const clear = lum(clearOn, i * 4) - lum(off, i * 4);
        if (clear < 0.05) continue;   /* the glitter itself */
        const expected = cloudSunlight(cloudValue(w[i * 4], w[i * 4 + 1], offset), threshold, c.opacity);
        if (expected < 0.99) shaded++;
        errs.push(Math.abs((lum(on, i * 4) - lum(off, i * 4)) / clear - expected));
      }
      check(backend, 'under a high sun a cloud\'s shade puts the glitter out as the pattern says', shaded > 200 && median(errs) < 0.02,
        { offset, glitterPixels: errs.length, shaded, medianError: r3(median(errs)), error90: r3(quantile(errs, 0.9)) });
    }

    /* THE OPEN SEA mirrors no far shore: only the band under the horizon changes, and it lightens */
    {
      const w = await where(LOW);
      const sea = await read(LOW), lake = await read({ ...LOW, seaOpen: false });
      let changed = 0, darker = 0, lowest = Infinity, lifted = 0;
      for (let i = 0; i < W * H; i++) {
        if (!isSea(w, i)) continue;
        const a = lum(sea, i * 4), b = lum(lake, i * 4);
        if (a === b) continue;
        changed++;
        if (a < b - 1e-4) darker++;
        lowest = Math.min(lowest, w[i * 4 + 2]);
        lifted = Math.max(lifted, a - b);
      }
      /* the lakes' wood stands in the reflection's lowest 2 degrees, read off a calmer surface: from 3 m up it reaches
         the water beyond about 80 m, and nearer where a ripple tilts the reflection down to it */
      check(backend, 'the open sea mirrors no far shore: only its reflected horizon changes, and only lighter',
        changed > 100 && darker === 0, { changed, darker, nearestChangeMetres: r3(lowest), mostLifted: r3(lifted) });
    }

    /* THE MIRROR warms the water toward a low sun, and leaves the water away from it as it was */
    {
      const midWhere = await where(MID);
      const warmth = px => { let r = 0, b = 0; for (let i = 0; i < W * H; i++) { if (!isSea(midWhere, i)) continue; r += px[i * 4]; b += px[i * 4 + 2]; } return r / b; };
      const toward = await read(MID), towardOff = await read({ ...MID, mirror: false });
      const away = await read({ ...MID, yaw: 180 }), awayOff = await read({ ...MID, yaw: 180, mirror: false });
      let awayMax = 0;
      for (let k = 0; k < away.length; k++) awayMax = Math.max(awayMax, Math.abs(away[k] - awayOff[k]));
      check(backend, 'the mirror warms the water toward a low sun and leaves it away from the sun', warmth(toward) > warmth(towardOff) * 1.02 && awayMax < 0.002,
        { towardWarmth: { mirror: r3(warmth(toward)), before: r3(warmth(towardOff)) }, awayMaxDiff: r3(awayMax) });
    }

    /* THE RELIEF shows the waves from above: the water's own contrast (each pixel against its four neighbours), near
       and far, and under a weak sun */
    {
      const contrast = (px, w, d0, d1) => {
        const v = [];
        for (let y = 1; y < H - 1; y++) for (let x = 1; x < W - 1; x++) {
          const i = y * W + x, d = w[i * 4 + 2];
          if (!isSea(w, i) || !isSea(w, i - 1) || !isSea(w, i + 1) || !isSea(w, i - W) || !isSea(w, i + W) || d < d0 || d >= d1) continue;
          v.push(Math.abs(lum(px, i * 4) - 0.25 * (lum(px, (i - 1) * 4) + lum(px, (i + 1) * 4) + lum(px, (i - W) * 4) + lum(px, (i + W) * 4))) / Math.max(1e-4, lum(px, i * 4)));
        }
        return v.length ? Math.round(median(v) * 1e5) / 1e5 : null;
      };
      const w = await where(STEEP), wFar = await where(STEEP_FAR);
      const on = await read(STEEP), off = await read({ ...STEEP, relief: false });
      const farOn = await read(STEEP_FAR), farOff = await read({ ...STEEP_FAR, relief: false });
      const weakOn = await read({ ...STEEP, preset: 'bluehour' }), weakOff = await read({ ...STEEP, preset: 'bluehour', relief: false });
      const rows = {
        fromAbove: { relief: contrast(on, w, 0, 1e6), before: contrast(off, w, 0, 1e6) },
        overviewNear: { relief: contrast(farOn, wFar, 0, 600), before: contrast(farOff, wFar, 0, 600) },
        overviewFar: { relief: contrast(farOn, wFar, 1500, 1e6), before: contrast(farOff, wFar, 1500, 1e6) },
        blueHour: { relief: contrast(weakOn, w, 0, 1e6), before: contrast(weakOff, w, 0, 1e6) } };
      const gain = r => r.relief - r.before;
      check(backend, 'the relief shows the waves from above, little far off and next to nothing under a weak sun',
        rows.fromAbove.relief > 3 * rows.fromAbove.before && gain(rows.overviewFar) < 0.25 * gain(rows.overviewNear)
          && gain(rows.blueHour) < 0.1 * gain(rows.fromAbove), rows);
    }

    /* STEADY FAR OFF: frames 1/30 s apart, the ripples on a 4 m/s westerly and the camera flying 21 m/s */
    {
      const state = createWaterMotion(), air = { x: 4, z: 0, ms: 4, axisX: 1, axisZ: 0 }, flows = [];
      for (let f = 0; f < 6; f++) { flows.push(state.flow.map(v => [...v])); stepWaterMotion(state, 1 / 30, air); }
      const w = await where(MID);
      const flicker = async variant => {
        const seq = [];
        for (let f = 0; f < 6; f++) seq.push(await read({ ...MID, ...variant, clouds: false, flow: flows[f], move: [0.5 * f, 0, 0.5 * f] }));
        const bands = {};
        for (const [name, d0, d1] of [['300-800 m', 300, 800], ['800-2000 m', 800, 2000], ['beyond 2 km', 2000, 1e6]]) {
          let change = 0, level = 0;
          for (let i = 0; i < W * H; i++) {
            const d = w[i * 4 + 2];
            if (!isSea(w, i) || d < d0 || d >= d1) continue;
            let m = 0; for (const s of seq) m += lum(s, i * 4); m /= seq.length;
            if (m < 0.35) continue;
            let c = 0; for (let f = 1; f < seq.length; f++) c += Math.abs(lum(seq[f], i * 4) - lum(seq[f - 1], i * 4));
            change += c / (seq.length - 1); level += m;
          }
          bands[name] = level > 0 ? r3(change / level) : null;
        }
        return bands;
      };
      const rows = { road: await flicker({}), mainGlow: await flicker(BEFORE) };
      check(backend, 'past 800 m the road is as steady as main\'s glow', rows.road['800-2000 m'] <= 0.01 && rows.road['beyond 2 km'] <= 0.01, rows);
    }

    check(backend, 'every read-back settled: two renders in a row agree', reads.every(r => r.settled),
      { reads: reads.length, mostRenders: Math.max(...reads.map(r => r.renders)) });
    check(backend, 'no page errors', errors.length === 0, { errors: errors.slice(0, 3) });

    /* PICTURES through the app's own tone mapping, and the desktop's glow */
    if (backend === 'webgl2') {
      const list = [];
      const shoot = async (label, options) => { await page.evaluate(o => window.__show(o), options); list.push({ label, png: (await page.locator('canvas').first().screenshot()).toString('base64') }); };
      await shoot('golden hour, 180 m: main', { ...OWNER, ...BEFORE });
      await shoot('golden hour, 180 m: the road', OWNER);
      await shoot('autumn, 180 m: main', { ...OWNER, preset: 'host', ...BEFORE });
      await shoot('autumn, 180 m: the road', { ...OWNER, preset: 'host' });
      await shoot('golden hour, 3 m: main', { ...LOW, ...BEFORE });
      await shoot('golden hour, 3 m: the road', LOW);
      await shoot('midnight sun, 40 m: main', { ...MID, preset: 'midnight', ...BEFORE });
      await shoot('midnight sun, 40 m: the road', { ...MID, preset: 'midnight' });
      await shoot('autumn, 45 degrees down: main', { ...STEEP, ...BEFORE });
      await shoot('autumn, 45 degrees down: relief', STEEP);
      await shoot('golden hour, 180 m, desktop glow: main', { ...OWNER, ...BEFORE, glow: true });
      await shoot('golden hour, 180 m, desktop glow: the road', { ...OWNER, glow: true });
      const jpg = await page.evaluate(async ({ list, cols }) => {
        const images = await Promise.all(list.map(async s => { const im = new Image(); im.src = `data:image/png;base64,${s.png}`; await im.decode(); return im; }));
        const w = images[0].width, h = images[0].height, c = document.createElement('canvas');
        c.width = w * cols; c.height = h * Math.ceil(images.length / cols);
        const g = c.getContext('2d');
        images.forEach((im, i) => {
          const x = (i % cols) * w, y = Math.floor(i / cols) * h;
          g.drawImage(im, x, y);
          g.font = '13px sans-serif';
          const tw = g.measureText(list[i].label).width + 10;
          g.fillStyle = 'rgba(0,0,0,.6)'; g.fillRect(x + 4, y + 4, tw, 20);
          g.fillStyle = '#fff'; g.fillText(list[i].label, x + 9, y + 18);
        });
        return c.toDataURL('image/jpeg', 0.88).split(',')[1];
      }, { list, cols: 4 });
      fs.writeFileSync(`${dir}/water.jpg`, Buffer.from(jpg, 'base64'));
      shots.water = list.map(s => s.label);
    }
    await browser.close();
  }
} finally {
  server.kill();
  fs.rmSync(generated, { force: true });
}
report.pictures = shots;
fs.writeFileSync(out, JSON.stringify(report, null, 1) + '\n');
console.log(failed ? 'isolated check FAILED' : `isolated check passed -> ${out}`);
process.exitCode = failed ? 1 : 0;
