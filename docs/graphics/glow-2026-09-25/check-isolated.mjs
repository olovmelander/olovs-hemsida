// The glow batch in isolated scenes (isolated.html), on WebGL2 and on WebGPU with
// reversed depth. What reaches the glow's threshold, preset by preset, measured
// on the player's own sky, clouds, haze, Nordic water, far wood, crowns, ground
// and bright paint, read back linear -- the colour the bloom's high pass takes --
// and sorted by what each pixel shows; with both befores and with the batch:
//  - the before: the player's sky with both befores is main's own, generated
//    from git at the baseline, pixel for pixel;
//  - with the batch, each preset's broad paint -- clear sky, haze, clouds away
//    from the sun, water, wood, crowns, rough, fairway, sand and path -- passes
//    nothing, and toward a low sun the clouds' shining centres cross;
//  - the ceilings glow.mjs reckons from the presets' paint are the ones measured;
//  - the lights without a low sun are untouched, value for value;
//  - the two backends agree;
// and pictures through the app's own pipeline (bloom, ACES with the dither).
// Software rendering by default, BANVY_GPU=1 for the real adapter. Run from the
// repository root: node docs/graphics/glow-2026-09-25/check-isolated.mjs
import fs from 'node:fs';
import { spawn, execFileSync } from 'node:child_process';
import { chromium } from 'playwright-core';
import { Color } from '../../../apps/golf/node_modules/three/build/three.webgpu.js';
import { browserArgs, browserExecutable, GPU } from '../../../tools/browser-args.mjs';
import { GLOW, glowThresholdOf, skyPaintCeiling } from '../../../apps/golf/src/engine/glow.mjs';
import { ATMOSPHERE_PRESETS } from '../../../apps/golf/src/engine/atmosphere-presets.mjs';
import { paintedAtmosphere } from '../../../apps/golf/src/engine/painted-world-palette.mjs';

const dir = 'docs/graphics/glow-2026-09-25';
const out = process.argv[2] || `${dir}/isolated-check.json`;
const baseline = '71d373e8';
const port = 8698;
const PRESETS = Object.keys(ATMOSPHERE_PRESETS);
const LOW_SUN = ['golden', 'dawn', 'midnight', 'host'];
const VIEWS = [['lake', ['sun', 'side', 'away']], ['crown', ['sun', 'side', 'away']], ['course', ['sun', 'away']]];
/* what must not glow: every broad surface, near the sun or not; the clouds near a low sun may */
const BROAD = /^(clear sky|cloud beyond 45°|water|far wood|shore|lawn|crown|trunk|rough|fairway|sand|path)/;

/* main's own sky at the baseline, as modules the page can import */
const gen = { painted: `${dir}/old-painted-sky.gen.mjs`, atmospheric: `${dir}/old-atmospheric-sky.gen.mjs` };
const show = path => execFileSync('git', ['show', `${baseline}:${path}`], { encoding: 'utf8' });
fs.writeFileSync(gen.painted, `// generated by check-isolated.mjs from ${baseline}; not committed\n${show('apps/golf/src/engine/painted-sky.mjs')}`);
fs.writeFileSync(gen.atmospheric, `// generated by check-isolated.mjs from ${baseline}; not committed\n${show('apps/golf/src/engine/atmospheric-sky.mjs')
  .replace("from './painted-sky.mjs'", "from './old-painted-sky.gen.mjs'")
  .replace("from './aerial-perspective.mjs'", "from '/apps/golf/src/engine/aerial-perspective.mjs'")}`);

const decode = (s, T) => { const b = Buffer.from(s, 'base64'); return new T(new Uint8Array(b).buffer); };
const smooth = (a, b, x) => { const t = Math.min(1, Math.max(0, (x - a) / (b - a))); return t * t * (3 - 2 * t); };
const lumOf = (c, k) => 0.2126 * c[k] + 0.7152 * c[k + 1] + 0.0722 * c[k + 2];
const r3 = v => Math.round(v * 1000) / 1000;
const painted = name => paintedAtmosphere(name, ATMOSPHERE_PRESETS[name]);
const finalFog = p => new Color(p.fog).lerp(new Color(p.paintedFog), 0.22);

/** A class's luminance spread, and what the bloom's high pass keeps of it at the threshold. */
function summarise(values, threshold) {
  if (!values.length) return { n: 0 };
  const v = Float64Array.from(values).sort();
  const q = f => v[Math.min(v.length - 1, Math.floor(f * (v.length - 1)))];
  let over = 0, kept = 0;
  for (const x of v) { if (x > threshold) over++; kept += smooth(threshold, threshold + GLOW.knee, x) * x; }
  return { n: v.length, p50: r3(q(0.5)), p90: r3(q(0.9)), p99: r3(q(0.99)), max: r3(v[v.length - 1]), over: r3(over / v.length), kept: r3(kept / v.length) };
}

/* each pixel's class, from its label and its ray */
function classes(kind, r) {
  const colour = decode(r.colour, Float32Array), label = decode(r.label, Uint8Array), rays = decode(r.rays, Float32Array);
  const [sx, sy, sz] = r.sun, sunAz = Math.atan2(sx, sz);
  const groups = {};
  const add = (name, value) => (groups[name] ||= []).push(value);
  for (let i = 0; i < label.length; i++) {
    const k = i * 4, lum = lumOf(colour, k), code = label[i];
    const [x, y, z] = [rays[k], rays[k + 1], rays[k + 2]];
    const angle = Math.acos(Math.max(-1, Math.min(1, x * sx + y * sy + z * sz))) * 180 / Math.PI;
    if (code === 1 || code === 2) {
      add(`${code === 1 ? 'clear sky' : 'cloud'} ${angle <= 15 ? 'within 15°' : angle <= 45 ? '15-45°' : 'beyond 45°'} of the sun`, lum);
      continue;
    }
    if (kind === 'lake') {
      if (code === r.codes.water) {
        let d = Math.atan2(x, z) - sunAz; d = Math.atan2(Math.sin(d), Math.cos(d));
        const metres = y < 0 ? 4 / -y * Math.hypot(x, z) : Infinity;
        add(Math.abs(d) < 6 * Math.PI / 180 ? `water, the sun's road ${metres < 300 ? 'near' : 'far'}` : 'water off the road', lum);
      } else add(code === r.codes.wood ? 'far wood' : 'shore', lum);
    } else if (kind === 'crown') add(code === r.codes.crown ? 'crown' : code === r.codes.trunk ? 'trunk' : 'lawn', lum);
    else if (code === r.codes.trim) add('white trim', lum);
    else if (code === r.codes.ball) add('white ball', lum);
    else if (code === r.codes.flag) add('flag yellow', lum);
    else if (y < 0) {
      const t = r.eye[1] / -y, hx = r.eye[0] + x * t, hz = r.eye[2] + z * t;
      const strip = Object.entries(r.strips).find(([, [a, b]]) => hx > a + 0.4 && hx < b - 0.4 && Math.abs(hz) < 9.6);
      const rough = !Object.values(r.strips).some(([a, b]) => hx > a - 0.6 && hx < b + 0.6 && Math.abs(hz) < 10.6);
      if (strip) add(strip[0], lum); else if (rough) add('rough', lum);
    }
  }
  return groups;
}

const server = spawn(process.execPath, ['tools/serve.mjs', '.', String(port)], { stdio: 'ignore' });
await new Promise(r => setTimeout(r, 1200));
const argsFor = b => b === 'webgpu' ? [...browserArgs(), '--enable-unsafe-webgpu',
  ...(GPU ? [] : ['--enable-features=Vulkan', '--use-vulkan=swiftshader', '--use-webgpu-adapter=swiftshader', '--disable-vulkan-surface'])] : browserArgs();
const report = { adapter: GPU ? 'gpu' : 'swiftshader', baseline, knee: GLOW.knee, backends: {} };
let failed = false;
const check = (backend, label, ok, detail) => {
  report.backends[backend].checks.push({ label, ok, ...detail });
  if (!ok) failed = true;
  console.log(`${backend} ${ok ? 'ok  ' : 'FAIL'} ${label} ${JSON.stringify(detail).slice(0, 600)}`);
};

try {
  for (const backend of ['webgl2', 'webgpu']) {
    report.backends[backend] = { checks: [], measured: {} };
    const browser = await chromium.launch({ ...browserExecutable(), args: argsFor(backend) });
    const page = await browser.newPage({ viewport: { width: 480, height: 270 } });
    const errors = [];
    page.on('pageerror', e => errors.push(String(e).slice(0, 400)));
    page.on('console', m => { if (m.type() === 'error') errors.push(m.text().slice(0, 400)); });
    await page.goto(`http://127.0.0.1:${port}/${dir}/isolated.html?backend=${backend}`, { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => window.__result, null, { timeout: 900000, polling: 500 });
    const ready = await page.evaluate(() => window.__result);
    if (!ready.ready) throw new Error(`${backend}: ${ready.error}`);
    const call = (fn, a) => page.evaluate(([f, x]) => window[f](x), [fn, a]);

    /* THE BEFORE: the player's sky with both befores is main's own */
    const pairs = {};
    for (const preset of PRESETS) for (const view of ['sun', 'away']) {
      const { now, main } = await call('__skyPair', { preset, view });
      const a = decode(now, Float32Array), b = decode(main, Float32Array);
      let differing = 0; for (let k = 0; k < a.length; k++) if (a[k] !== b[k]) differing++;
      pairs[`${preset} ${view}`] = differing;
    }
    check(backend, 'the sky with both befores is main\'s own, value for value, in every preset toward the sun and away',
      Object.values(pairs).every(n => n === 0), { differingValues: pairs });

    /* THE MEASUREMENT, with both befores and with the batch */
    const measured = report.backends[backend].measured;
    for (const preset of PRESETS) for (const before of [true, false]) {
      const row = (measured[preset] ||= {})[before ? 'before' : 'after'] = {};
      for (const [kind, views] of VIEWS) for (const view of views) {
        const r = await call('__read', { kind, preset, view, before });
        row.threshold = r.threshold;
        row[`${kind} ${view}`] = Object.fromEntries(Object.entries(classes(kind, r)).map(([k, v]) => [k, summarise(v, r.threshold)]));
      }
    }
    const each = (row, test) => { const hits = []; for (const [view, groups] of Object.entries(row)) if (view !== 'threshold') for (const [k, s] of Object.entries(groups)) if (test(k, s)) hits.push({ view, class: k, ...s }); return hits; };

    /* the thresholds are the presets' own, and 0.86 before */
    check(backend, 'each preset\'s threshold is its own with the batch and 0.86 with the befores',
      PRESETS.every(n => measured[n].after.threshold === glowThresholdOf(painted(n)) && measured[n].before.threshold === GLOW.threshold),
      { thresholds: Object.fromEntries(PRESETS.map(n => [n, measured[n].after.threshold])) });

    /* before the batch, a low sun's glow found only the greens' sheen and sunlit white */
    const beforeGlow = Object.fromEntries(LOW_SUN.map(n => [n, each(measured[n].before, (k, s) => s.over > 0).map(h => `${h.class} (${h.view}): ${h.over}`)]));
    check(backend, 'before the batch nothing in a low sun\'s sky, water, wood or crowns reached 0.86: only the greens\' sheen and sunlit white',
      LOW_SUN.every(n => each(measured[n].before, (k, s) => s.over > 0 && !/^(green|white|flag)/.test(k)).length === 0), { beforeGlow });

    /* with the batch the broad paint passes nothing, and the clouds toward a low sun cross */
    const broad = Object.fromEntries(PRESETS.map(n => [n, each(measured[n].after, (k, s) => BROAD.test(k) && s.n > 50 && s.kept > 0.001)
      .map(h => `${h.class} (${h.view}): kept ${h.kept}`)]));
    check(backend, 'with the batch no preset\'s broad paint glows: clear sky, haze, far clouds, water, wood, crowns, rough, fairway, sand, path',
      PRESETS.every(n => n === 'noon' || broad[n].length === 0), { broad });
    const sunward = Object.fromEntries(LOW_SUN.map(n => {
      const clouds = each(measured[n].after, (k, s) => /^cloud (within 15°|15-45°)/.test(k) && s.n > 50);
      return [n, { max: Math.max(...clouds.map(c => c.max)), over: Math.max(...clouds.map(c => c.over)) }];
    }));
    check(backend, 'toward a low sun the clouds\' shining centres cross the threshold, half way into the knee and more',
      LOW_SUN.every(n => sunward[n].max >= glowThresholdOf(painted(n)) + 0.5 * GLOW.knee && sunward[n].over > 0.02), { sunward });

    /* the ceilings glow.mjs reckons from the paint are the measured ones: the brightest sky pixel before the batch */
    const ceilings = Object.fromEntries(PRESETS.map(n => {
      const sky = each(measured[n].before, k => /^(clear sky|cloud)/.test(k)).map(h => h.max);
      return [n, { measured: Math.max(...sky), reckoned: r3(skyPaintCeiling(painted(n), finalFog(painted(n)))) }];
    }));
    check(backend, 'the sky\'s paint ceilings glow.mjs reckons are the measured ones, within 0.02',
      Object.values(ceilings).every(c => Math.abs(c.measured - c.reckoned) <= 0.02), { ceilings });

    /* the lights without a low sun: untouched */
    const untouched = PRESETS.filter(n => !LOW_SUN.includes(n));
    check(backend, 'noon, blue hour, storm and mist are untouched: every class the same with the batch as without',
      untouched.every(n => JSON.stringify(measured[n].after) === JSON.stringify(measured[n].before)), { presets: untouched });

    check(backend, 'no page errors', errors.length === 0, { errors: errors.slice(0, 3) });

    /* PICTURES, through the app's own pipeline: the lake toward the sun, and the glow alone */
    if (backend === 'webgl2') {
      const compose = async (shots, file) => {
        const jpg = await page.evaluate(async shots => {
          const images = await Promise.all(shots.map(async s => { const im = new Image(); im.src = `data:image/png;base64,${s.png}`; await im.decode(); return im; }));
          const w = images[0].width, h = images[0].height, c = document.createElement('canvas');
          c.width = w * 2; c.height = h * Math.ceil(images.length / 2);
          const g = c.getContext('2d');
          images.forEach((im, i) => {
            const x = (i % 2) * w, y = Math.floor(i / 2) * h;
            g.drawImage(im, x, y);
            g.font = '14px sans-serif';
            const width = g.measureText(shots[i].label).width + 12;
            g.fillStyle = 'rgba(0,0,0,.55)'; g.fillRect(x + 6, y + 6, width, 22);
            g.fillStyle = '#fff'; g.fillText(shots[i].label, x + 12, y + 22);
          });
          return c.toDataURL('image/jpeg', 0.88).split(',')[1];
        }, shots);
        fs.writeFileSync(`${dir}/${file}`, Buffer.from(jpg, 'base64'));
      };
      const NAMES = { golden: 'golden hour', dawn: 'dawn', midnight: 'midnight sun', host: 'autumn' };
      const shoot = async (label, options) => { await call('__picture', options); return { label, png: (await page.locator('canvas').first().screenshot()).toString('base64') }; };
      const lakes = [], alone = [];
      for (const preset of LOW_SUN) for (const before of [true, false]) lakes.push(await shoot(`${NAMES[preset]}, ${before ? 'before' : 'with the glow'}`, { kind: 'lake', preset, view: 'sun', before }));
      for (const preset of ['golden', 'dawn']) for (const before of [true, false])
        alone.push(await shoot(`${NAMES[preset]}, ${before ? 'before' : 'with the batch'}: the glow alone, x4`, { kind: 'lake', preset, view: 'sun', before, glowOnly: 4 }));
      await compose(lakes, 'lakes.jpg');
      await compose(alone, 'glow-alone.jpg');
    }
    await browser.close();
  }

  /* the backends agree: every class's spread, preset by preset, with the batch */
  const [a, b] = ['webgl2', 'webgpu'].map(k => report.backends[k].measured);
  let worst = { d: 0 };
  for (const n of PRESETS) for (const [view, groups] of Object.entries(a[n].after)) if (view !== 'threshold') for (const [k, s] of Object.entries(groups)) {
    const t = b[n].after[view]?.[k];
    if (!t || s.n < 500 || t.n < 500) continue;
    for (const q of ['p50', 'p90', 'p99']) { const d = Math.abs(s[q] - t[q]); if (d > worst.d) worst = { d: r3(d), preset: n, view, class: k, q }; }
  }
  report.backendsAgree = worst;
  const agree = worst.d <= 0.02;
  if (!agree) failed = true;
  console.log(`${agree ? 'ok  ' : 'FAIL'} WebGL2 and WebGPU agree: largest difference in a class's p50/p90/p99 ${JSON.stringify(worst)}`);
} finally {
  server.kill();
  fs.rmSync(gen.painted, { force: true });
  fs.rmSync(gen.atmospheric, { force: true });
}
fs.writeFileSync(out, JSON.stringify(report, null, 1) + '\n');
console.log(failed ? 'isolated check FAILED' : `isolated check passed -> ${out}`);
process.exitCode = failed ? 1 : 0;
