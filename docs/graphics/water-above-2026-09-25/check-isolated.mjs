// The water from above in isolated scenes (isolated.html): the player's own water
// beside ground lit as the player lights it, with its sky, haze, cloud shadows,
// wind patches and tone mapping, on WebGL2 and on WebGPU with reversed depth:
//  - the before: with both befores the player's water is main's own
//    (water-shading.mjs and water-road.mjs generated from git at the baseline),
//    value for value;
//  - the cloud shade: seen straight down from the Ovan view's heights, each water
//    pixel's body keeps exactly mix(share, 1, the sun the cloud leaves), its relief
//    giving way with the sun, while what the water reflects is untouched; the
//    share is the one the lit ground beside it keeps, so the shade crosses the
//    shoreline; under a high sun it holds from a low eye too, and under a low sun
//    a low eye sees the water unchanged;
//  - the patches from above: the body a little lighter over a gusty patch and a
//    little darker over a calm one, exactly as reckoned, and the waves' relief as
//    rough as the patch (never under half), within its cap; none from a low eye.
// Each read-back is drawn until two renders in a row agree. The body's share of a
// pixel is read by painting the body black (what remains is the reflection and
// the haze over it) and taking that away. And pictures through the app's own
// tone mapping. Software rendering by default, BANVY_GPU=1 for the real adapter.
// Run from the repository root: node docs/graphics/water-above-2026-09-25/check-isolated.mjs
