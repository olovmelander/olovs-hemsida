for (const shared of ['nordic-water.mjs', 'painted-world-lighting.mjs', 'cloud-shadow.mjs', 'aerial-perspective.mjs', 'water-lighting.mjs'])
  execFileSync('git', ['diff', '--quiet', baseline, '--', `apps/golf/src/engine/${shared}`]);
