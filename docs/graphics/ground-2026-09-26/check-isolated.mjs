// The ground batch in isolated scenes (isolated.html): a hole on the app's own
// exact-edge atlas and ground material, and the ground cover built from the
// app's own blades and rules with main.js's materials, on WebGL2 and on WebGPU
// with reversed depth, beside main's own ground material -- generated from git
// at the baseline, drawn in the same page over the same atlas and textures:
//  - the before: with ?groundedges=0, ?stripereach=0 and ?hardground=0 the
//    ground is main's, pixel for pixel, from the tee, from above, beside a path
//    and over the mud, lit and in its classes' categorical colours;
//  - the edges: in the app's hole view the rough beyond 150 m reads as rough,
//    where main's took a share of every class; a fairway's side running down
//    the view is at most three pixels of blend at 150, 175 and 320 m, where
//    main's spread over many;
//  - the stripes' reach: from above the fairway's wide section, past 32 m from
//    the line main's passes hold one flat tone and the batch's fade out; within
//    26 m they are main's, to a half float's last bit;
//  - the hard ground: beside a path main's fairway darkened the path's edge as
//    a taller cut; the batch's does not, and nothing else there moves; the mud
//    takes the hard ground's finish;
//  - the cover: with the sun behind the eye the tussocks, clumps and reeds are
//    lit on the side that is seen, where main's were dark; a block's shadow
//    falls on the tussocks, where main's stayed sunlit; the tussocks' colour is
//    back where it was tuned (on the detail texture as it was then); the mown
//    edge's clumps take autumn's ochre;
// and pictures through the app's tone mapping, main beside the batch: the hole
// view (main.js's own, 41 m up and 74 m behind the tee) lit and in the classes' colours,
// from the tee, the wide fairway from above, and the cover. Each
// read-back is drawn until two renders in a row agree. Software rendering by
// default, BANVY_GPU=1 for the real adapter.
// Run from the repository root: node docs/graphics/ground-2026-09-26/check-isolated.mjs
