// The crowns' cut through the MSAA samples (docs/tree-sparkle-2026-09-28.md) in
// an isolated page (isolated.html): the player's own Hero trees, all five
// species in rows from 60 m to 480 m against a golden-hour sky, drawn through
// 4x MSAA on WebGL2 and on WebGPU with reversed depth, with three crown cuts --
// main's material, generated from git at the baseline; the before
// (?crowncoverage=0); and the cut through the samples. The camera pans in
// steps of 0.015 degrees (about a seventh of a pixel), and:
//  - the before is main's, value for value, in every frame;
//  - the flashes: pixels whose display luminance jumps from one step to the
//    next while their neighbours hold (the glitter meter's flips), by strength,
//    fewer with the cut through the samples, and the strongest far fewer;
//  - the crowns' area (the mask, 1 - coverage, exactly) is the hard cut's
//    within one per cent, and it holds steadier from step to step;
//  - away from the crowns' edges nothing changes: where both cuts cover the
//    whole pixel the colour is the same;
//  - the frame stays opaque: no pixel's alpha falls under 1 (coverage written
//    as alpha would leave dark hollow outlines);
//  - no page or console error: the cut compiles on both backends.
// Software rendering by default, BANVY_GPU=1 for the real adapter.
// Run from the repository root: node docs/graphics/tree-sparkle-2026-09-28/check-isolated.mjs
import fs from 'node:fs';
import { spawn, execFileSync } from 'node:child_process';
import { chromium } from 'playwright-core';
import { browserArgs, browserExecutable, GPU } from '../../../tools/browser-args.mjs';

const dir = 'docs/graphics/tree-sparkle-2026-09-28';
const out = process.argv[2] || `${dir}/isolated-check.json`;
const baseline = 'f05006e8';
const port = 8771;
const W = 640, H = 400, STEPS = 12, YAW = 0.015;
const BACKENDS = (process.env.BANVY_BACKENDS || 'webgl2,webgpu').split(',');
const report = { adapter: GPU ? 'gpu' : 'swiftshader', baseline, size: [W, H], steps: STEPS, yawDegrees: YAW, backends: {} };
let failed = false;
const r4 = v => Math.round(v * 10000) / 10000;

/* main's crown material, from git; every module it imports is main's own */
execFileSync('git', ['diff', '--quiet', baseline, '--', 'apps/golf/src/engine/painted-world-palette.mjs']);
fs.writeFileSync(`${dir}/main-ghibli-foliage-material.gen.mjs`,
  `// generated by check-isolated.mjs from ghibli-foliage-material.mjs at ${baseline}; not committed\n` +
  execFileSync('git', ['show', `${baseline}:apps/golf/src/engine/ghibli-foliage-material.mjs`], { encoding: 'utf8' })
    .replaceAll("from './", "from '../../../apps/golf/src/engine/")
    .replaceAll("from 'three/webgpu'", "from '../../../apps/golf/node_modules/three/build/three.webgpu.js'")
    .replaceAll("from 'three/tsl'", "from '../../../apps/golf/node_modules/three/build/three.tsl.js'"));

/* three's ACES (the player's output, before its dither) and the sRGB encode: display luminance 0..255 */
const aces = v => {
  const m = [v[0] * 0.59719 + v[1] * 0.35458 + v[2] * 0.04823, v[0] * 0.07600 + v[1] * 0.90834 + v[2] * 0.01566, v[0] * 0.02840 + v[1] * 0.13383 + v[2] * 0.83777];
  const f = x => (x * (x + 0.0245786) - 0.000090537) / (x * (0.983729 * x + 0.4329510) + 0.238081);
  const r = m.map(f);
  return [1.60475 * r[0] - 0.53108 * r[1] - 0.07367 * r[2], -0.10208 * r[0] + 1.10813 * r[1] - 0.00605 * r[2], -0.00327 * r[0] - 0.07276 * r[1] + 1.07602 * r[2]]
    .map(x => Math.min(1, Math.max(0, x)));
};
const srgb = x => x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055;
const EXPOSURE = 1.12;   /* golden hour's */
const display = px => {
  const L = new Float32Array(W * H);
  for (let i = 0; i < W * H; i++) {
    const c = aces([px[i * 4], px[i * 4 + 1], px[i * 4 + 2]].map(v => v * EXPOSURE / 0.6)).map(srgb);
    L[i] = 255 * (0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2]);
  }
  return L;
};
/* the glitter meter's flip: moved by > 40/255 while the eight neighbours moved by < 10 on average */
const flips = (a, b) => {
  const s = { all: 0, over80: 0, over120: 0 };
  for (let y = 1; y < H - 1; y++) for (let x = 1; x < W - 1; x++) {
    const i = y * W + x, d = Math.abs(a[i] - b[i]);
    if (d <= 40) continue;
    let nb = 0;
    for (const o of [-W - 1, -W, -W + 1, -1, 1, W - 1, W, W + 1]) nb += Math.abs(a[i + o] - b[i + o]);
    if (nb / 8 >= 10) continue;
    s.all++; if (d > 80) s.over80++; if (d > 120) s.over120++;
  }
  return s;
};

const server = spawn(process.execPath, ['tools/serve.mjs', '.', String(port)], { stdio: 'ignore' });
try {
  await new Promise(r => setTimeout(r, 1200));
  const argsFor = backend => backend === 'webgpu' ? [...browserArgs(), '--enable-unsafe-webgpu',
    ...(GPU ? [] : ['--enable-features=Vulkan', '--use-vulkan=swiftshader', '--use-webgpu-adapter=swiftshader', '--disable-vulkan-surface'])] : browserArgs();
  const check = (backend, label, ok, detail) => {
    report.backends[backend].checks.push({ label, ok, ...detail });
    if (!ok) failed = true;
    console.log(`${backend} ${ok ? 'ok  ' : 'FAIL'} ${label} ${JSON.stringify(detail).slice(0, 900)}`);
  };
  const decode = s => { const b = Buffer.from(s, 'base64'); return new Float32Array(new Uint8Array(b).buffer); };
  /* rgba rows, row 0 at the top whatever the backend's row order */
  const topDown = (px, backend) => {
    if (backend !== 'webgl2') return px;
    const o = new Float32Array(px.length);
    for (let row = 0; row < H; row++) o.set(px.subarray((H - 1 - row) * W * 4, (H - row) * W * 4), row * W * 4);
    return o;
  };

  for (const backend of BACKENDS) {
    report.backends[backend] = { checks: [] };
    const browser = await chromium.launch({ ...browserExecutable(), args: argsFor(backend) });
    const errors = [];
    const page = await browser.newPage({ viewport: { width: W, height: H } });
    page.on('pageerror', e => errors.push(String(e).slice(0, 300)));
    page.on('console', m => { if (m.type() === 'error') errors.push(m.text().slice(0, 300)); });
    await page.goto(`http://127.0.0.1:${port}/${dir}/isolated.html?backend=${backend}&w=${W}&h=${H}`, { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => window.__result, null, { timeout: 900000, polling: 500 });
    const ready = await page.evaluate(() => window.__result);
    if (!ready.ready) throw new Error(`${backend}: ${ready.error}`);
    report.backends[backend].page = ready;
    const frame = async (cut, step, mask) => topDown(decode(await page.evaluate(o => window.__frame(o), { cut, yaw: step * YAW, mask })), backend);

    const cuts = {};
    for (const cut of ['main', 'before', 'coverage']) {
      const colour = [], masks = [];
      for (let s = 0; s <= STEPS; s++) { colour.push(await frame(cut, s, false)); masks.push(await frame(cut, s, true)); }
      cuts[cut] = { colour, masks };
    }
    /* the before is main's, value for value */
    let beforeDiff = 0;
    for (let s = 0; s <= STEPS; s++) for (const kind of ['colour', 'masks']) {
      const a = cuts.main[kind][s], b = cuts.before[kind][s];
      for (let i = 0; i < a.length; i++) beforeDiff = Math.max(beforeDiff, Math.abs(a[i] - b[i]));
    }
    check(backend, 'the before (?crowncoverage=0) is main\'s crown, value for value, in every frame, colour and mask', beforeDiff === 0, { maxDiff: beforeDiff });

    const measured = {};
    for (const cut of ['before', 'coverage']) {
      const L = cuts[cut].colour.map(display);
      const steps = [];
      for (let s = 1; s <= STEPS; s++) steps.push(flips(L[s - 1], L[s]));
      const sum = key => steps.reduce((a, r) => a + r[key], 0) / STEPS;
      /* the crowns' area, in pixels: 1 - the mask, exactly */
      const areas = cuts[cut].masks.map(m => { let a = 0; for (let i = 0; i < W * H; i++) a += 1 - m[i * 4]; return a; });
      const mean = areas.reduce((a, b) => a + b, 0) / areas.length;
      /* the area's change from step to step, as a share of it */
      const churn = areas.slice(1).reduce((a, v, s) => a + Math.abs(v - areas[s]), 0) / STEPS / mean;
      /* each pixel's coverage change from step to step: in all (the area the silhouette
         sweeps, the same however it is cut) and in whole-pixel flips (all sky to all
         crown or back, what reads as a sparkle) */
      let shimmer = 0, wholeFlips = 0;
      for (let s = 1; s <= STEPS; s++) {
        const a = cuts[cut].masks[s - 1], b = cuts[cut].masks[s];
        for (let i = 0; i < W * H; i++) { const d = Math.abs(a[i * 4] - b[i * 4]); shimmer += d; if (d >= 0.75) wholeFlips++; }
      }
      let minAlpha = 1;
      for (const px of cuts[cut].colour) for (let i = 3; i < px.length; i += 4) minAlpha = Math.min(minAlpha, px[i]);
      measured[cut] = { flipsPerStep: r4(sum('all')), over80PerStep: r4(sum('over80')), over120PerStep: r4(sum('over120')),
        area: Math.round(mean), areaChurnPerStep: r4(churn), shimmerPerStep: Math.round(shimmer / STEPS),
        wholeFlipsPerStep: r4(wholeFlips / STEPS), minAlpha: r4(minAlpha) };
    }
    report.backends[backend].measured = measured;
    const [b, c] = [measured.before, measured.coverage];
    check(backend, 'the flashes: fewer through the samples, and the strongest (over 120/255) far fewer',
      c.flipsPerStep < b.flipsPerStep && c.over120PerStep <= 0.5 * b.over120PerStep && c.over80PerStep < b.over80PerStep, { before: b, coverage: c });
    check(backend, 'the crowns keep the hard cut\'s area within one per cent', Math.abs(c.area - b.area) / b.area < 0.01,
      { before: b.area, coverage: c.area, change: r4((c.area - b.area) / b.area) });
    check(backend, 'the silhouette moves by parts of a pixel: whole-pixel flips far fewer, over the same swept area',
      c.wholeFlipsPerStep <= 0.5 * b.wholeFlipsPerStep && Math.abs(c.shimmerPerStep - b.shimmerPerStep) <= 0.05 * b.shimmerPerStep,
      { before: { wholeFlips: b.wholeFlipsPerStep, swept: b.shimmerPerStep }, coverage: { wholeFlips: c.wholeFlipsPerStep, swept: c.shimmerPerStep } });
    /* the crowns' colour: over the pixels the crowns cover, weighted by coverage, the mean
       colour of what the trees add over the sky is the same (the cut shares edges between
       samples; it does not repaint the leaves) */
    const SKY = [0.82, 0.42, 0.18];   /* isolated.html's sky, linear */
    const crownMean = cut => {
      const sum = [0, 0, 0]; let w = 0;
      for (let s = 0; s <= STEPS; s += 4) {
        const m = cuts[cut].masks[s], px = cuts[cut].colour[s];
        /* above the horizon (row 247 for this camera), where only sky lies behind the trees */
        for (let i = 0; i < 235 * W; i++) {
          const c = 1 - m[i * 4];
          if (c <= 0) continue;
          w += c;
          for (let ch = 0; ch < 3; ch++) sum[ch] += px[i * 4 + ch] - (1 - c) * SKY[ch];
        }
      }
      return sum.map(v => v / w);
    };
    const [mb, mc] = [crownMean('before'), crownMean('coverage')];
    const worst = Math.max(...mb.map((v, ch) => Math.abs(mc[ch] - v) / v));
    check(backend, 'the crowns keep their colour: the mean over the pixels they cover within one per cent', worst < 0.01,
      { before: mb.map(r4), coverage: mc.map(r4), worstShare: r4(worst) });
    check(backend, 'the frame stays opaque: no pixel\'s alpha under 1', c.minAlpha >= 0.999 && b.minAlpha >= 0.999, { before: b.minAlpha, coverage: c.minAlpha });
    check(backend, 'the cut through the samples is on for the new crowns and off for main\'s and the before',
      Object.values(ready.coverage).every(v => v.coverage === true && v.before === false && v.main === false), { coverage: ready.coverage });
    check(backend, 'no page or console error', errors.length === 0, { errors: errors.slice(0, 3) });
    await browser.close();
  }
  /* the backends agree on what the cut does */
  if (report.backends.webgl2?.measured && report.backends.webgpu?.measured) {
    const g = report.backends.webgl2.measured, p = report.backends.webgpu.measured;
    report.backendsAgree = { areaChange: [r4((g.coverage.area - g.before.area) / g.before.area), r4((p.coverage.area - p.before.area) / p.before.area)],
      over120Share: [r4(g.coverage.over120PerStep / Math.max(g.before.over120PerStep, 1e-9)), r4(p.coverage.over120PerStep / Math.max(p.before.over120PerStep, 1e-9))] };
    console.log('backends', JSON.stringify(report.backendsAgree));
  }
} finally {
  server.kill();
}
fs.writeFileSync(out, JSON.stringify(report, null, 1) + '\n');
console.log(failed ? 'isolated check FAILED' : `isolated check passed -> ${out}`);
process.exitCode = failed ? 1 : 0;
