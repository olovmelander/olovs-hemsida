// The nine lights after the audit in an isolated scene (isolated.html): ground,
// trees, a lake and a lamp lit as the player lights them, on WebGL2 and on WebGPU
// with reversed depth, beside main's own light -- main's presets, palette and
// aerial perspective, generated from git at the baseline, over the same trees,
// atlas and textures in the same page (its fog node takes the scene's, in
// programs of its own: two nodes in one program pass WebGPU's sixteen
// inter-stage variables in the impostors, and two page loads bake the impostor
// atlas at different moments of the trees' sway, so neither compares main):
//  - the before: with ?lights=before every light is main's, value for value --
//    its painted atmosphere on the CPU, and every pixel of the scene from the tee
//    and over the woods toward the sun -- and the lights the audit left alone
//    (the summer day, mist, autumn) are main's as they are;
//  - the blue hour: its sky brighter than its land, where main's was darker, and
//    the land cooler and less saturated;
//  - golden hour: the ground from the tee and from above lighter than main's;
//  - the storm: its deck of broad, soft forms (the sky's spread of brightness,
//    toward the sun) far calmer than main's spots, and a greyer, wet ground;
//  - dawn: the land less saturated and warmer, in its rose; the midnight sun: the
//    land warmer, in its gold;
//  - noon: its sun at 55 degrees;
//  - the glaze gives way over a lamp pushed past white: the lamp keeps its colour
//    to the half-float read-back's precision while the land around it takes it;
// and pictures through the app's tone mapping and high quality's glow, main
// beside now, with each picture's measures. Each read-back is drawn until two
// renders in a row agree. Software rendering by default, BANVY_GPU=1 for the
// real adapter.
// Run from the repository root: node docs/graphics/lights-2026-09-25/check-isolated.mjs
import fs from 'node:fs';
import { spawn, execFileSync } from 'node:child_process';
import { chromium } from 'playwright-core';
import { browserArgs, browserExecutable, GPU } from '../../../tools/browser-args.mjs';
import { ATMOSPHERE_PRESETS } from '../../../apps/golf/src/engine/atmosphere-presets.mjs';
import { paintedAtmosphere } from '../../../apps/golf/src/engine/painted-world-palette.mjs';

const dir = 'docs/graphics/lights-2026-09-25';
const out = process.argv[2] || `${dir}/isolated-check.json`;
const baseline = '381a3a5b';
const port = 8726;
/* a portrait view whose rows are whole 256-byte blocks in both read-backs (8 bytes a pixel in half float, 16 in
   float): WebGPU copies a texture out in such blocks, and a row that ends mid-block skews every row after it */
const W = 384, H = 640;
const BACKENDS = (process.env.BANVY_BACKENDS || 'webgl2,webgpu').split(',');
const LIGHTS = Object.keys(ATMOSPHERE_PRESETS);
const AUDITED = ['bluehour', 'golden', 'storm', 'dawn', 'midnight', 'noon'];
const UNTOUCHED = LIGHTS.filter(name => !AUDITED.includes(name));
const NAMES = { golden: 'Kväll', noon: 'Dag', summer: 'Sommar', dawn: 'Gryning', midnight: 'Midnattssol', bluehour: 'Blå timmen', storm: 'Oväder', mist: 'Dis', host: 'Höst' };
const report = { adapter: GPU ? 'gpu' : 'swiftshader', baseline, backends: {} };
let failed = false;
const r4 = v => Math.round(v * 10000) / 10000;

/* ------------------------------------------------------------------ MAIN'S LIGHT, FROM GIT */
/* the modules the audit changed, as main has them, importing what they import from here (in the browser and in Node alike) */
const CHANGED = ['atmosphere-presets.mjs', 'painted-world-palette.mjs', 'aerial-perspective.mjs'];
/* every other module the page draws with is main's own */
const PAGE_MODULES = ['atmospheric-sky.mjs', 'ghibli-tree-assets.mjs', 'ghibli-foliage-material.mjs', 'crown-depth.mjs', 'tree-impostor.mjs',
  'shadow-tint.mjs', 'cloud-shadow.mjs', 'stand-tint.mjs', 'geom.js', 'material.js', 'water-shading.mjs', 'nordic-water.mjs',
  'water-normal-texture.mjs', 'ground-detail-upload.mjs', 'water-lighting.mjs', 'painted-world-lighting.mjs', 'output-dither.mjs',
  'water-road.mjs', 'water-above.mjs', 'lighting-environment.mjs', 'glow.mjs'];
execFileSync('git', ['diff', '--quiet', baseline, '--', ...PAGE_MODULES.map(f => `apps/golf/src/engine/${f}`)]);
const generated = CHANGED.map(file => `${dir}/main-${file.replace('.mjs', '')}.gen.mjs`);
CHANGED.forEach((file, i) => fs.writeFileSync(generated[i], `// generated by check-isolated.mjs from ${file} at ${baseline}; not committed\n${
  execFileSync('git', ['show', `${baseline}:apps/golf/src/engine/${file}`], { encoding: 'utf8' })
    .replaceAll("from './", "from '../../../apps/golf/src/engine/")
    .replaceAll("from 'three/webgpu'", "from '../../../apps/golf/node_modules/three/build/three.webgpu.js'")
    .replaceAll("from 'three/tsl'", "from '../../../apps/golf/node_modules/three/build/three.tsl.js'")}`));

/* a light's values in one order, undefined dropped: the painted atmosphere as data */
const canonical = v => JSON.stringify(v, (key, x) => x && typeof x === 'object' && !Array.isArray(x)
  ? Object.fromEntries(Object.keys(x).sort().filter(k => x[k] !== undefined).map(k => [k, x[k]])) : x);
const server = spawn(process.execPath, ['tools/serve.mjs', '.', String(port)], { stdio: 'ignore' });
try {
  const main = {
    presets: (await import(`../../../${generated[0]}`)).ATMOSPHERE_PRESETS,
    paintedAtmosphere: (await import(`../../../${generated[1]}`)).paintedAtmosphere,
  };
  const mainPainted = name => main.paintedAtmosphere(name, main.presets[name]);
  /* THE BEFORE, AS DATA: every light with ?lights=before is main's, and the lights the audit left alone are main's as they are */
  {
    const rows = {};
    for (const name of LIGHTS) {
      const then = canonical(mainPainted(name)), before = canonical(paintedAtmosphere(name, ATMOSPHERE_PRESETS[name], { before: true }));
      const now = paintedAtmosphere(name, ATMOSPHERE_PRESETS[name]), m = mainPainted(name);
      rows[name] = { beforeIsMain: before === then, nowIsMain: canonical(now) === then,
        changed: Object.keys({ ...now, ...m }).filter(k => canonical(now[k]) !== canonical(m[k])).sort() };
    }
    const ok = LIGHTS.every(n => rows[n].beforeIsMain) && UNTOUCHED.every(n => rows[n].nowIsMain) && AUDITED.every(n => !rows[n].nowIsMain);
    report.data = { ok, rows };
    console.log(`${ok ? 'ok  ' : 'FAIL'} with ?lights=before every light is main's, value for value, and the summer day, mist and autumn are main's as they are ${JSON.stringify(rows).slice(0, 600)}`);
    if (!ok) failed = true;
  }

  await new Promise(r => setTimeout(r, 1200));
  const argsFor = backend => backend === 'webgpu' ? [...browserArgs(), '--enable-unsafe-webgpu',
    ...(GPU ? [] : ['--enable-features=Vulkan', '--use-vulkan=swiftshader', '--use-webgpu-adapter=swiftshader', '--disable-vulkan-surface'])] : browserArgs();
  const check = (backend, label, ok, detail) => {
    report.backends[backend].checks.push({ label, ok, ...detail });
    if (!ok) failed = true;
    console.log(`${backend} ${ok ? 'ok  ' : 'FAIL'} ${label} ${JSON.stringify(detail).slice(0, 900)}`);
  };
  const decode = s => { const b = Buffer.from(s, 'base64'); return new Float32Array(new Uint8Array(b).buffer); };
  const compare = (a, b) => {
    let differing = 0, max = 0;
    for (let i = 0; i < W * H; i++) {
      let d = 0;
      for (let c = 0; c < 3; c++) d = Math.max(d, Math.abs(a[i * 4 + c] - b[i * 4 + c]));
      if (d > 0) differing++;
      if (d > max) max = d;
    }
    return { differing, maxDiff: r4(max) };
  };
  const lum = (px, i) => 0.2126 * px[i * 4] + 0.7152 * px[i * 4 + 1] + 0.0722 * px[i * 4 + 2];
  /* a band of the frame, counted from the top whatever the backend's row order: its mean luminance, its spread and
     saturation (linear), and its mean colour */
  const band = (px, backend, from, to) => {
    let n = 0, L = 0, L2 = 0, S = 0; const rgb = [0, 0, 0];
    for (let row = 0; row < H; row++) {
      const top = backend === 'webgl2' ? H - 1 - row : row;
      if (top < from * H || top >= to * H) continue;
      for (let x = 0; x < W; x++) {
        const i = row * W + x, l = lum(px, i), r = px[i * 4], g = px[i * 4 + 1], b = px[i * 4 + 2], mx = Math.max(r, g, b), mn = Math.min(r, g, b);
        n++; L += l; L2 += l * l; S += mx > 0 ? (mx - mn) / mx : 0; rgb[0] += r; rgb[1] += g; rgb[2] += b;
      }
    }
    const mean = L / n;
    return { mean: r4(mean), spread: r4(Math.sqrt(Math.max(0, L2 / n - mean * mean)) / Math.max(mean, 1e-6)), saturation: r4(S / n), rgb: rgb.map(v => r4(v / n)) };
  };

  for (const backend of BACKENDS) {
    report.backends[backend] = { checks: [] };
    const browser = await chromium.launch({ ...browserExecutable(), args: argsFor(backend) });
    const page = await browser.newPage({ viewport: { width: W, height: H } });
    const errors = [];
    page.on('pageerror', e => errors.push(String(e).slice(0, 300)));
    page.on('console', m => { if (m.type() === 'error') errors.push(m.text().slice(0, 300)); });
    await page.goto(`http://127.0.0.1:${port}/${dir}/isolated.html?backend=${backend}&w=${W}&h=${H}`, { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => window.__result, null, { timeout: 900000, polling: 500 });
    const ready = await page.evaluate(() => window.__result);
    if (!ready.ready || !ready.main) throw new Error(`${backend}: ${ready.error || 'main\'s light missing'}`);
    const reads = [];
    const read = async options => {
      const r = await page.evaluate(o => window.__read(o), options);
      reads.push({ settled: r.settled, renders: r.renders });
      return decode(r.px);
    };

    /* THE BEFORE: every light with ?lights=before is main's, pixel for pixel; the untouched lights are as they are */
    const mainReads = {};
    {
      const rows = {};
      for (const name of LIGHTS) for (const view of ['tee', 'toward']) {
        const theirs = await read({ preset: name, view, version: 'main' });
        mainReads[`${name}/${view}`] = theirs;
        rows[`${name}/${view}`] = { before: compare(await read({ preset: name, view, before: true }), theirs) };
        if (UNTOUCHED.includes(name)) rows[`${name}/${view}`].now = compare(await read({ preset: name, view }), theirs);
      }
      check(backend, 'with ?lights=before every light is main\'s, pixel for pixel, and the summer day, mist and autumn are main\'s as they are',
        Object.values(rows).every(r => r.before.differing === 0 && (!r.now || r.now.differing === 0)), rows);
    }

    /* THE AUDITED LIGHTS, NOW AGAINST MAIN: the sky (the top fifth from the tee) and the ground (its lowest two fifths), from above,
       and the storm's sky alone toward the sun */
    const m = {};
    for (const name of AUDITED) {
      m[name] = {};
      for (const version of ['main', 'now']) {
        const tee = version === 'main' ? mainReads[`${name}/tee`] : await read({ preset: name, view: 'tee' });
        const above = await read({ preset: name, view: 'above', version });
        m[name][version] = { sky: band(tee, backend, 0, 0.2), ground: band(tee, backend, 0.6, 1), above: band(above, backend, 0, 1) };
        if (name === 'storm') m[name][version].deck = band(await read({ preset: name, view: 'sun', skyOnly: true, version }), backend, 0, 0.8);
      }
    }
    const warmth = b => b.rgb[0] / b.rgb[1];
    check(backend, 'the blue hour: its sky brighter than its land, where main\'s was darker, and the land cooler and less saturated',
      m.bluehour.now.sky.mean > 1.5 * m.bluehour.now.ground.mean && m.bluehour.main.sky.mean < m.bluehour.main.ground.mean
      && m.bluehour.now.ground.saturation < 0.85 * m.bluehour.main.ground.saturation
      && m.bluehour.now.ground.rgb[2] / m.bluehour.now.ground.rgb[1] > 1.5 * m.bluehour.main.ground.rgb[2] / m.bluehour.main.ground.rgb[1], m.bluehour);
    check(backend, 'golden hour: the ground from the tee and from above lighter than main\'s',
      m.golden.now.ground.mean > 1.15 * m.golden.main.ground.mean && m.golden.now.above.mean > 1.1 * m.golden.main.above.mean, m.golden);
    check(backend, 'the storm: a calmer deck than main\'s spots, and a greyer ground',
      m.storm.now.deck.spread < 0.6 * m.storm.main.deck.spread && m.storm.now.ground.saturation < 0.8 * m.storm.main.ground.saturation, m.storm);
    check(backend, 'dawn: the land less saturated and warmer, in its rose; the midnight sun: the land warmer, in its gold',
      m.dawn.now.ground.saturation < 0.95 * m.dawn.main.ground.saturation && warmth(m.dawn.now.ground) > 1.05 * warmth(m.dawn.main.ground)
      && warmth(m.midnight.now.ground) > 1.08 * warmth(m.midnight.main.ground), { dawn: m.dawn, midnight: m.midnight });
    check(backend, 'noon: its sun at 55 degrees, the course from above within a few percent of main\'s',
      Math.abs(Math.asin(ATMOSPHERE_PRESETS.noon.dir[1] / Math.hypot(...ATMOSPHERE_PRESETS.noon.dir)) * 180 / Math.PI - 55) < 0.5
      && Math.abs(m.noon.now.above.mean / m.noon.main.above.mean - 1) < 0.08, m.noon);

    /* THE GLAZE GIVES WAY OVER A LAMP: in the blue hour the lamp keeps its colour while the land takes the glaze */
    {
      const lit = await read({ preset: 'bluehour', view: 'tee', lamp: true });
      const bare = await read({ preset: 'bluehour', view: 'tee', lamp: true, over: { glaze: undefined } });
      let lampPixels = 0, lampMax = 0, landDiffering = 0;
      for (let i = 0; i < W * H; i++) {
        let d = 0;
        for (let c = 0; c < 3; c++) d = Math.max(d, Math.abs(lit[i * 4 + c] - bare[i * 4 + c]) / Math.max(bare[i * 4 + c], 1e-3));
        if (bare[i * 4] > 3) { lampPixels++; lampMax = Math.max(lampMax, d); } else if (d > 0) landDiffering++;
      }
      check(backend, 'the glaze gives way over a lamp pushed past white: the lamp keeps its colour while the land takes the glaze',
        lampPixels > 100 && lampMax < 0.002 && landDiffering > 0.25 * W * H, { lampPixels, lampMaxRelative: r4(lampMax), landDiffering });
    }

    report.backends[backend].measures = m;
    report.backends[backend].reads = { count: reads.length, settled: reads.filter(r => r.settled).length, maxRenders: Math.max(...reads.map(r => r.renders)) };
    check(backend, 'every read-back settled', reads.every(r => r.settled), report.backends[backend].reads);
    check(backend, 'no page or console error', errors.filter(e => !e.includes('404')).length === 0, { errors: errors.slice(0, 3) });
    await browser.close();
  }

  /* PICTURES, through the app's tone mapping and high quality's glow: main beside now, and each picture's measures (sRGB, 0-255) */
  {
    const PW = 480, PH = 320;
    const browser = await chromium.launch({ ...browserExecutable(), args: argsFor('webgl2') });
    const page = await browser.newPage({ viewport: { width: PW, height: PH } });
    await page.goto(`http://127.0.0.1:${port}/${dir}/isolated.html?backend=webgl2&w=${PW}&h=${PH}`, { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => window.__result, null, { timeout: 900000, polling: 500 });
    const MEASURE = async png => {
      const im = new Image(); im.src = `data:image/png;base64,${png}`; await im.decode();
      const c = document.createElement('canvas'); c.width = im.width; c.height = im.height;
      const g = c.getContext('2d'); g.drawImage(im, 0, 0);
      const d = g.getImageData(0, 0, im.width, im.height).data;
      const region = (y0, y1) => {
        let n = 0, L = 0, S = 0;
        for (let y = Math.floor(y0 * im.height); y < Math.floor(y1 * im.height); y++) for (let x = 0; x < im.width; x++) {
          const i = (y * im.width + x) * 4, r = d[i], gg = d[i + 1], b = d[i + 2], mx = Math.max(r, gg, b), mn = Math.min(r, gg, b);
          n++; L += 0.2126 * r + 0.7152 * gg + 0.0722 * b; S += mx ? (mx - mn) / mx : 0;
        }
        return { mean: +(L / n).toFixed(1), saturation: +(S / n).toFixed(3) };
      };
      return { frame: region(0, 1), sky: region(0, 0.2), ground: region(0.6, 1) };
    };
    const second = { bluehour: 'toward', golden: 'above', storm: 'toward', dawn: 'away', midnight: 'toward', noon: 'above' };
    const shots = [], pictures = {};
    for (const name of AUDITED) for (const view of ['tee', second[name]]) for (const version of ['main', 'now']) {
      await page.evaluate(o => window.__show(o), { preset: name, view, version });
      const png = (await page.locator('canvas').first().screenshot()).toString('base64');
      (pictures[`${name}/${view}`] ??= {})[version] = await page.evaluate(MEASURE, png);
      shots.push({ label: `${NAMES[name]}, ${view === 'above' ? 'Ovan' : view}: ${version}`, png });
    }
    report.pictures = pictures;
    const jpg = await page.evaluate(async ({ list, cols }) => {
      const images = await Promise.all(list.map(async s => { const im = new Image(); im.src = `data:image/png;base64,${s.png}`; await im.decode(); return im; }));
      const w = images[0].width, h = images[0].height, c = document.createElement('canvas');
      c.width = w * cols; c.height = h * Math.ceil(images.length / cols);
      const g = c.getContext('2d');
      images.forEach((im, i) => {
        const x = (i % cols) * w, y = Math.floor(i / cols) * h;
        g.drawImage(im, x, y);
        g.font = '13px sans-serif';
        const tw = g.measureText(list[i].label).width + 10;
        g.fillStyle = 'rgba(0,0,0,.6)'; g.fillRect(x + 4, y + 4, tw, 20);
        g.fillStyle = '#fff'; g.fillText(list[i].label, x + 9, y + 18);
      });
      return c.toDataURL('image/jpeg', 0.86).split(',')[1];
    }, { list: shots, cols: 4 });
    fs.writeFileSync(`${dir}/lights.jpg`, Buffer.from(jpg, 'base64'));
    await browser.close();
  }

  /* THE BACKENDS AGREE on every measure */
  if (BACKENDS.length > 1) {
    const [a, b] = BACKENDS.map(k => report.backends[k]);
    const pairs = [];
    const walk = (x, y, path) => {
      if (typeof x === 'number' && typeof y === 'number') { if (!Number.isInteger(x) || Math.abs(x) < 1) pairs.push({ path, a: x, b: y, d: Math.abs(x - y) }); return; }
      if (x && y && typeof x === 'object') for (const key of Object.keys(x)) walk(x[key], y[key], `${path}.${key}`);
    };
    walk(a.measures, b.measures, 'measures');
    a.checks.forEach((row, i) => walk(row, b.checks[i], row.label));
    const worst = pairs.reduce((mx, p) => (p.d > mx.d ? p : mx), { d: 0 });
    const ok = pairs.every(p => p.d < 0.01 || /maxDiff|lampMax/.test(p.path));
    report.agreement = { measures: pairs.length, worst };
    console.log(`backends ${ok ? 'agree' : 'DISAGREE'} over ${pairs.length} measures; worst ${JSON.stringify(worst)}`);
    if (!ok) failed = true;
  }
} finally {
  server.kill();
  for (const file of generated) fs.rmSync(file, { force: true });
}
fs.writeFileSync(out, JSON.stringify(report, null, 1) + '\n');
console.log(failed ? 'isolated check FAILED' : `isolated check passed -> ${out}`);
process.exitCode = failed ? 1 : 0;
