// The summer day in an isolated scene (isolated.html): ground, trees and a lake
// lit as the player lights them, under the player's painted sky, on WebGL2 and on
// WebGPU with reversed depth:
//  - every other light is main's, value for value: its painted atmosphere, its
//    glow threshold and the ceiling of its sky's paint (the modules at the
//    baseline, generated from git), and the haze the continuous ocean keeps;
//  - no clouds: the summer sky does not depend on its cloud field at all -- with
//    the field scaled and raised elsewhere every pixel is the same, value for
//    value, the sky alone toward the sun and straight up and the whole scene --
//    where noon's clouds move;
//  - no cloud shadows: with the shadows' pattern moved elsewhere every pixel of
//    the ground, trees and lake is the same, where noon's move;
//  - the glow: the brightest of the summer sky's paint, toward the sun, stays
//    under the glow's threshold by its margin, so the sky never glows; what
//    crosses it in the scene is reported beside noon's;
//  - straight up, the sky is the summer's zenith colour;
// and pictures through the app's tone mapping and glow, Dag beside Sommar.
// Each read-back is drawn until two renders in a row agree. Software rendering
// by default, BANVY_GPU=1 for the real adapter.
// Run from the repository root: node docs/graphics/summer-2026-09-25/check-isolated.mjs
import fs from 'node:fs';
import { spawn, execFileSync } from 'node:child_process';
import { Color } from '../../../apps/golf/node_modules/three/build/three.webgpu.js';
import { chromium } from 'playwright-core';
import { browserArgs, browserExecutable, GPU } from '../../../tools/browser-args.mjs';
import { ATMOSPHERE_PRESETS } from '../../../apps/golf/src/engine/atmosphere-presets.mjs';
import { paintedAtmosphere } from '../../../apps/golf/src/engine/painted-world-palette.mjs';
import { GLOW, glowThresholdOf, skyPaintCeiling } from '../../../apps/golf/src/engine/glow.mjs';

const dir = 'docs/graphics/summer-2026-09-25';
const out = process.argv[2] || `${dir}/isolated-check.json`;
const baseline = 'db2cc9bb';
const port = 8723;
/* a portrait view whose rows are whole 256-byte blocks in both read-backs (8 bytes a pixel in half float, 16 in
   float): WebGPU copies a texture out in such blocks, and a row that ends mid-block skews every row after it */
const W = 384, H = 640;
const BACKENDS = (process.env.BANVY_BACKENDS || 'webgl2,webgpu').split(',');
const painted = name => paintedAtmosphere(name, ATMOSPHERE_PRESETS[name]);
const report = { adapter: GPU ? 'gpu' : 'swiftshader', baseline, backends: {} };
let failed = false;
const r4 = v => Math.round(v * 10000) / 10000;

/* ------------------------------------------------------------------ EVERY OTHER LIGHT IS MAIN'S */
/* the light's modules at the baseline, importing what they import from here */
const fromMain = file => execFileSync('git', ['show', `${baseline}:apps/golf/src/engine/${file}`], { encoding: 'utf8' });
const generated = [`${dir}/main-atmosphere-presets.gen.mjs`, `${dir}/main-painted-world-palette.gen.mjs`, `${dir}/main-glow.gen.mjs`];
fs.writeFileSync(generated[0], `// generated by check-isolated.mjs from atmosphere-presets.mjs at ${baseline}; not committed\n${fromMain('atmosphere-presets.mjs')}`);
fs.writeFileSync(generated[1], `// generated by check-isolated.mjs from painted-world-palette.mjs at ${baseline}; not committed\n${fromMain('painted-world-palette.mjs')}`);
fs.writeFileSync(generated[2], `// generated by check-isolated.mjs from glow.mjs at ${baseline}; not committed\n${
  fromMain('glow.mjs').replaceAll("from './", "from '../../../apps/golf/src/engine/")
    .replace("from 'three/webgpu'", "from '../../../apps/golf/node_modules/three/build/three.webgpu.js'")}`);
try {
  const main = {
    presets: (await import(`../../../${generated[0]}`)).ATMOSPHERE_PRESETS,
    painted: (await import(`../../../${generated[1]}`)).paintedAtmosphere,
    glow: await import(`../../../${generated[2]}`),
  };
  /* the fog as setPreset leaves it: toward the painted fog */
  const fogOf = p => new Color(p.fog).lerp(new Color(p.paintedFog), 0.22);
  /* the continuous ocean's haze (main.js setPreset): noon's raised to 0.00022 before, every light's at least that now */
  const oceanBefore = (name, p) => (name === 'noon' ? 0.00022 : p.dens), oceanNow = p => Math.max(p.dens, 0.00022);
  const rows = {};
  for (const name of Object.keys(main.presets)) {
    const now = painted(name), then = main.painted(name, main.presets[name]);
    rows[name] = {
      painted: JSON.stringify(now) === JSON.stringify(then),
      glowThreshold: glowThresholdOf(now) === main.glow.glowThresholdOf(then),
      skyPaintCeiling: skyPaintCeiling(now, fogOf(now)) === main.glow.skyPaintCeiling(then, fogOf(then)),
      oceanHaze: oceanNow(now) === oceanBefore(name, then),
    };
  }
  const added = Object.keys(ATMOSPHERE_PRESETS).filter(name => !(name in main.presets));
  const ok = Object.values(rows).every(r => Object.values(r).every(Boolean)) && JSON.stringify(added) === '["summer"]';
  report.otherLights = { ok, added, rows };
  console.log(`${ok ? 'ok  ' : 'FAIL'} every other light is main's, value for value; added ${JSON.stringify(added)}`);
  if (!ok) failed = true;
} finally {
  for (const file of generated) fs.rmSync(file, { force: true });
}

/* ------------------------------------------------------------------ IN THE RENDERER */
const summer = painted('summer'), noon = painted('noon');
report.summer = { threshold: glowThresholdOf(summer), margin: GLOW.margin, skyPaintCeiling: r4(skyPaintCeiling(summer, new Color(summer.fog).lerp(new Color(summer.paintedFog), 0.22))),
  zenith: new Color(summer.skyZenith).toArray().map(r4) };
/* the cloud field elsewhere: scaled and raised */
const fieldMoved = p => ({ cloudScale: p.cloudScale * 1.7, cloudElevation: Math.min(1, p.cloudElevation + 0.3) });
/* the clouds' shadows elsewhere: the page's own offset is (900, 300) */
const SHADOWS_MOVED = [2300, 1700];
const server = spawn(process.execPath, ['tools/serve.mjs', '.', String(port)], { stdio: 'ignore' });
await new Promise(r => setTimeout(r, 1200));
const argsFor = backend => backend === 'webgpu' ? [...browserArgs(), '--enable-unsafe-webgpu',
  ...(GPU ? [] : ['--enable-features=Vulkan', '--use-vulkan=swiftshader', '--use-webgpu-adapter=swiftshader', '--disable-vulkan-surface'])] : browserArgs();
const check = (backend, label, ok, detail) => {
  report.backends[backend].checks.push({ label, ok, ...detail });
  if (!ok) failed = true;
  console.log(`${backend} ${ok ? 'ok  ' : 'FAIL'} ${label} ${JSON.stringify(detail).slice(0, 700)}`);
};
const decode = s => { const b = Buffer.from(s, 'base64'); return new Float32Array(new Uint8Array(b).buffer); };
/* how two read-backs differ: pixels with any channel apart, and the largest difference */
const compare = (a, b) => {
  let differing = 0, max = 0;
  for (let i = 0; i < W * H; i++) {
    let d = 0;
    for (let c = 0; c < 3; c++) d = Math.max(d, Math.abs(a[i * 4 + c] - b[i * 4 + c]));
    if (d > 0) differing++;
    if (d > max) max = d;
  }
  return { differing, share: r4(differing / (W * H)), maxDiff: r4(max) };
};
const lum = (px, i) => 0.2126 * px[i * 4] + 0.7152 * px[i * 4 + 1] + 0.0722 * px[i * 4 + 2];
/* the brightest pixel and where it lies, counted from the top of the frame: WebGL2 reads rows from the bottom */
const brightest = (px, backend) => {
  let best = 0, at = 0;
  for (let i = 0; i < W * H; i++) { const l = lum(px, i); if (l > best) { best = l; at = i; } }
  const row = Math.floor(at / W);
  return { luminance: r4(best), x: at % W, fromTop: backend === 'webgl2' ? H - 1 - row : row };
};
const above = (px, t) => { let n = 0; for (let i = 0; i < W * H; i++) if (lum(px, i) > t) n++; return r4(n / (W * H)); };

try {
  for (const backend of BACKENDS) {
    report.backends[backend] = { checks: [] };
    const browser = await chromium.launch({ ...browserExecutable(), args: argsFor(backend) });
    const page = await browser.newPage({ viewport: { width: W, height: H } });
    const errors = [];
    page.on('pageerror', e => errors.push(String(e).slice(0, 300)));
    page.on('console', m => { if (m.type() === 'error') errors.push(m.text().slice(0, 300)); });
    await page.goto(`http://127.0.0.1:${port}/${dir}/isolated.html?backend=${backend}&w=${W}&h=${H}`, { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => window.__result, null, { timeout: 900000, polling: 500 });
    const ready = await page.evaluate(() => window.__result);
    if (!ready.ready) throw new Error(`${backend}: ${ready.error}`);
    const reads = [];
    const read = async options => {
      const r = await page.evaluate(o => window.__read(o), options);
      reads.push({ settled: r.settled, renders: r.renders });
      return decode(r.px);
    };

    /* NO CLOUDS: the summer sky, with its cloud field scaled and raised elsewhere, value for value; noon's moves */
    {
      const rows = {};
      for (const [name, view] of [['the sky toward the sun', { view: 'sun', skyOnly: true }], ['the sky straight up', { view: 'zenith', skyOnly: true }],
        ['the tee', { view: 'tee' }], ['the flyover', { view: 'flyover' }]]) {
        const own = await read({ preset: 'summer', ...view }), moved = await read({ preset: 'summer', ...view, over: fieldMoved(summer) });
        const noonOwn = await read({ preset: 'noon', ...view }), noonMoved = await read({ preset: 'noon', ...view, over: fieldMoved(noon) });
        rows[name] = { summer: compare(own, moved), noon: compare(noonOwn, noonMoved) };
      }
      /* noon's control is the wide sky toward the sun: straight up, a narrow patch of its field may hold no cloud either way */
      check(backend, 'the summer sky has no clouds: with its cloud field elsewhere every pixel is the same, where noon\'s clouds move',
        Object.values(rows).every(r => r.summer.differing === 0) && rows['the sky toward the sun'].noon.share > 0.2, rows);
    }

    /* NO CLOUD SHADOWS: with their pattern moved every pixel of the ground, trees and lake is the same; noon's move */
    {
      const rows = {};
      for (const [name, view] of [['straight down (Ovan)', { view: 'above' }], ['the flyover', { view: 'flyover' }], ['over the lake', { view: 'glitter' }]]) {
        const own = await read({ preset: 'summer', ...view }), moved = await read({ preset: 'summer', ...view, cloudOffset: SHADOWS_MOVED });
        const noonOwn = await read({ preset: 'noon', ...view }), noonMoved = await read({ preset: 'noon', ...view, cloudOffset: SHADOWS_MOVED });
        rows[name] = { summer: compare(own, moved), noon: compare(noonOwn, noonMoved) };
      }
      check(backend, 'no cloud shadows: with their pattern elsewhere every pixel is the same, where noon\'s move',
        Object.values(rows).every(r => r.summer.differing === 0 && r.noon.share > 0.05), rows);
    }

    /* THE GLOW: the summer sky's paint, brightest toward the sun, under the threshold by its margin; what crosses it in the scene */
    {
      const sky = await read({ preset: 'summer', view: 'sun', skyOnly: true }), noonSky = await read({ preset: 'noon', view: 'sun', skyOnly: true });
      /* per view, the share of the frame over each light's threshold and the brightest pixel */
      const scene = {};
      for (const view of ['tee', 'flyover', 'lake', 'glitter', 'green', 'above']) {
        const s = await read({ preset: 'summer', view }), n = await read({ preset: 'noon', view });
        scene[view] = { summer: { over: above(s, glowThresholdOf(summer)), peak: brightest(s, backend).luminance },
          noon: { over: above(n, glowThresholdOf(noon)), peak: brightest(n, backend).luminance } };
      }
      const top = brightest(sky, backend);
      check(backend, 'the summer sky never glows: its brightest paint, toward the sun, is under the glow\'s threshold by its margin',
        top.luminance < glowThresholdOf(summer) - GLOW.margin,
        { threshold: glowThresholdOf(summer), margin: GLOW.margin, brightest: top, noonSkyBrightest: brightest(noonSky, backend), scene });
    }

    /* STRAIGHT UP: the summer's zenith colour */
    {
      const px = await read({ preset: 'summer', view: 'zenith', skyOnly: true });
      const want = new Color(summer.skyZenith).multiplyScalar(summer.paintedSkyExposure ?? 1);
      const at = [W / 2 - 1, W / 2].flatMap(x => [H / 2 - 1, H / 2].map(y => y * W + x));
      const got = [0, 1, 2].map(c => at.reduce((s, i) => s + px[i * 4 + c], 0) / at.length);
      const error = Math.max(...got.map((v, c) => Math.abs(v - [want.r, want.g, want.b][c]) / [want.r, want.g, want.b][c]));
      check(backend, 'straight up, the sky is the summer\'s zenith colour', error < 0.005, { got: got.map(r4), want: [want.r, want.g, want.b].map(r4), error: r4(error) });
    }

    report.backends[backend].reads = { count: reads.length, settled: reads.filter(r => r.settled).length, maxRenders: Math.max(...reads.map(r => r.renders)) };
    check(backend, 'every read-back settled', reads.every(r => r.settled), report.backends[backend].reads);
    check(backend, 'no page or console error', errors.filter(e => !e.includes('404')).length === 0, { errors: errors.slice(0, 3) });
    await browser.close();
  }

  /* PICTURES, through the app's tone mapping and high quality's glow: Dag beside Sommar */
  {
    const PW = 480, PH = 320;
    const browser = await chromium.launch({ ...browserExecutable(), args: argsFor('webgl2') });
    const page = await browser.newPage({ viewport: { width: PW, height: PH } });
    await page.goto(`http://127.0.0.1:${port}/${dir}/isolated.html?backend=webgl2&w=${PW}&h=${PH}`, { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => window.__result, null, { timeout: 900000, polling: 500 });
    const shots = [];
    for (const [view, label] of [['tee', 'from the tee'], ['flyover', 'a flyover'], ['lake', 'across the lake'], ['glitter', 'the sun on the lake'], ['green', 'over the green']]) {
      for (const [preset, name] of [['noon', 'Dag'], ['summer', 'Sommar']]) {
        await page.evaluate(o => window.__show(o), { preset, view });
        shots.push({ label: `${name}, ${label}`, png: (await page.locator('canvas').first().screenshot()).toString('base64') });
      }
    }
    const jpg = await page.evaluate(async ({ list, cols }) => {
      const images = await Promise.all(list.map(async s => { const im = new Image(); im.src = `data:image/png;base64,${s.png}`; await im.decode(); return im; }));
      const w = images[0].width, h = images[0].height, c = document.createElement('canvas');
      c.width = w * cols; c.height = h * Math.ceil(images.length / cols);
      const g = c.getContext('2d');
      images.forEach((im, i) => {
        const x = (i % cols) * w, y = Math.floor(i / cols) * h;
        g.drawImage(im, x, y);
        g.font = '13px sans-serif';
        const tw = g.measureText(list[i].label).width + 10;
        g.fillStyle = 'rgba(0,0,0,.6)'; g.fillRect(x + 4, y + 4, tw, 20);
        g.fillStyle = '#fff'; g.fillText(list[i].label, x + 9, y + 18);
      });
      return c.toDataURL('image/jpeg', 0.88).split(',')[1];
    }, { list: shots, cols: 2 });
    fs.writeFileSync(`${dir}/summer.jpg`, Buffer.from(jpg, 'base64'));
    await browser.close();
  }

  /* THE BACKENDS AGREE on every share and colour they measured */
  if (BACKENDS.length > 1) {
    const [a, b] = BACKENDS.map(k => report.backends[k].checks);
    const pairs = [];
    const walk = (x, y, path) => {
      if (typeof x === 'number' && typeof y === 'number') { if (!Number.isInteger(x) || Math.abs(x) < 1) pairs.push({ path, a: x, b: y, d: Math.abs(x - y) }); return; }
      if (x && y && typeof x === 'object') for (const key of Object.keys(x)) walk(x[key], y[key], `${path}.${key}`);
    };
    a.forEach((row, i) => walk(row, b[i], row.label));
    const worst = pairs.reduce((m, p) => (p.d > m.d ? p : m), { d: 0 });
    /* the positive controls' shares and differences depend on each backend's rasterisation, and where a brightest pixel
       lies is no measure of colour (a tie may fall either side): the sky and colours may not differ */
    const ok = pairs.every(p => p.d < 0.01 || /noon|maxDiff|share|\.over$|\.x$|fromTop/.test(p.path));
    report.agreement = { measures: pairs.length, worst };
    console.log(`backends ${ok ? 'agree' : 'DISAGREE'} over ${pairs.length} measures; worst ${JSON.stringify(worst)}`);
    if (!ok) failed = true;
  }
} finally {
  server.kill();
}
fs.writeFileSync(out, JSON.stringify(report, null, 1) + '\n');
console.log(failed ? 'isolated check FAILED' : `isolated check passed -> ${out}`);
process.exitCode = failed ? 1 : 0;
